#!/usr/bin/env node

import { CodegenPostProcessError, GenerateConfig, runGenerateCli } from "@beep/codegen-kit";
import { $AcpId } from "@beep/identity";
import { Effect, pipe } from "effect";
import * as A from "effect/Array";
import * as S from "effect/Schema";
import type { ExtraRenderer, SpecSource } from "@beep/codegen-kit";

const CURRENT_SCHEMA_RELEASE = "v0.11.3";
const packageRoot = `${import.meta.dirname}/..`;
const releaseBaseUrl = `https://github.com/agentclientprotocol/agent-client-protocol/releases/download/${CURRENT_SCHEMA_RELEASE}`;
const $I = $AcpId.create("scripts/generate");

class MetaJson extends S.Class<MetaJson>($I`MetaJson`)(
  {
    agentMethods: S.Record(S.String, S.String),
    clientMethods: S.Record(S.String, S.String),
    version: S.Union([S.Finite, S.String]),
  },
  $I.annote("MetaJson", {
    description: "ACP upstream metadata JSON consumed by the package-specific extra renderer.",
  })
) {}

const metaSource: SpecSource = {
  _tag: "url",
  url: `${releaseBaseUrl}/meta.unstable.json`,
  pin: CURRENT_SCHEMA_RELEASE,
  cachePath: `${packageRoot}/spec/meta.unstable.json`,
};

const generatedHeader = pipe(
  [
    "/**",
    " * Generated ACP protocol schema and metadata modules.",
    " *",
    " * @packageDocumentation",
    " * @since 0.0.0",
    " */",
    "",
    "// This file is generated by the @beep/acp package. Do not edit manually.",
    `// Current ACP schema release: ${CURRENT_SCHEMA_RELEASE}`,
  ],
  A.join("\n")
);

const renderMetaConst = (name: string, value: string, description: string): string =>
  pipe(
    [
      "/**",
      ` * ${description}`,
      " *",
      ` * **Example** (Read ${name})`,
      " *",
      " * ```ts",
      ` * import { ${name} } from "@beep/acp/schema"`,
      " *",
      ` * console.log(${name})`,
      " * ```",
      " *",
      " * @category constants",
      " * @since 0.0.0",
      " */",
      `export const ${name} = ${value} as const;`,
    ],
    A.join("\n")
  );

const decodeMeta = S.decodeUnknownEffect(MetaJson);
const encodeAgentMethods = S.encodeUnknownEffect(S.fromJsonString(MetaJson.fields.agentMethods));
const encodeClientMethods = S.encodeUnknownEffect(S.fromJsonString(MetaJson.fields.clientMethods));
const encodeVersion = S.encodeUnknownEffect(S.fromJsonString(MetaJson.fields.version));

const renderMeta: ExtraRenderer = Effect.fn("Acp.generateMeta")(function* (_config, refresh, fetch) {
  const document = yield* fetch(metaSource, refresh);
  const meta = yield* decodeMeta(document).pipe(
    Effect.mapError((cause) => CodegenPostProcessError.make({ message: "Could not decode ACP metadata cache", cause }))
  );
  const agentMethods = yield* encodeAgentMethods(meta.agentMethods).pipe(
    Effect.mapError((cause) => CodegenPostProcessError.make({ message: "Could not render AGENT_METHODS", cause }))
  );
  const clientMethods = yield* encodeClientMethods(meta.clientMethods).pipe(
    Effect.mapError((cause) => CodegenPostProcessError.make({ message: "Could not render CLIENT_METHODS", cause }))
  );
  const version = yield* encodeVersion(meta.version).pipe(
    Effect.mapError((cause) => CodegenPostProcessError.make({ message: "Could not render PROTOCOL_VERSION", cause }))
  );
  return pipe(
    [
      generatedHeader,
      "",
      'import { $AcpId } from "@beep/identity";',
      "",
      'const $I = $AcpId.create("_generated/meta.gen");',
      "void $I;",
      "",
      renderMetaConst("AGENT_METHODS", agentMethods, "Generated ACP agent method lookup table."),
      "",
      renderMetaConst("CLIENT_METHODS", clientMethods, "Generated ACP client method lookup table."),
      "",
      renderMetaConst("PROTOCOL_VERSION", version, "Generated ACP protocol version."),
      "",
    ],
    A.join("\n")
  );
});

const config = GenerateConfig.make({
  packageName: "@beep/acp",
  identity: { composer: "$AcpId", moduleId: "_generated/schema.gen" },
  source: {
    _tag: "url",
    url: `${releaseBaseUrl}/schema.unstable.json`,
    pin: CURRENT_SCHEMA_RELEASE,
    cachePath: `${packageRoot}/spec/schema.unstable.json`,
  },
  dialect: "json-schema-2020-12",
  transforms: ["nullableTypeArray", "flattenAllOfRefVariants", "distributeUnionSiblings"],
  format: "schemas",
  output: {
    path: `${packageRoot}/src/_generated/schema.gen.ts`,
    header: generatedHeader,
  },
  extraModules: [{ renderer: "acp-meta", path: `${packageRoot}/src/_generated/meta.gen.ts` }],
});

runGenerateCli(config, { extraRenderers: { "acp-meta": renderMeta } });
