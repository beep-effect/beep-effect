/**
 * The projection of each pool's cap that the standing missed-event check
 * reads, rendered as a generated module inside repo-cli.
 *
 * **Details**
 *
 * The production configuration in `Config.ts` is the one source of truth for
 * a pool's `maximumCount`. repo-cli may not depend on an `infra` package, so
 * the check reads a generated copy instead:
 * `packages/tooling/tool/cli/src/commands/Ci/FleetPoolCaps.generated.ts`.
 * `fleet-pool-caps.ts` at this package's root writes it, and a test fails
 * when the committed copy differs from {@link renderFleetPoolCapsModule} of
 * {@link productionConfig}.
 *
 * @packageDocumentation
 * @category configuration
 * @since 0.0.0
 */

import * as A from "effect/Array";
import * as S from "effect/Schema";
import * as Str from "effect/String";
import { effectiveCap, FleetPhase, PoolName, PoolSettings, productionConfig } from "./Config.ts";
import { $InfraCiRunnersId } from "./internal/InfraCiRunnersId.ts";
import type { CiRunnersConfig } from "./Config.ts";

const $I = $InfraCiRunnersId.create("FleetPoolCaps");

const Cap = S.Int.check(S.isGreaterThanOrEqualTo(0)).pipe(
  $I.annoteSchema("FleetPoolCap", { description: "A pool's runner cap: zero or more." })
);

/**
 * One pool's label and its cap in each phase.
 *
 * **Example** (Project the production heavy pool)
 *
 * ```ts
 * import { projectFleetPoolCaps } from "@beep/infra-ci-runners/FleetPoolCaps"
 * import { productionConfig } from "@beep/infra-ci-runners/Config"
 *
 * const heavy = projectFleetPoolCaps(productionConfig).pools[0]
 * console.log(heavy?.label) // "beep-fleet-heavy"
 * ```
 *
 * @category models
 * @since 0.0.0
 */
export const FleetPoolCapProjection = S.Struct({
  pool: PoolName,
  label: S.String,
  overlap: Cap,
  primary: Cap,
}).pipe($I.annoteSchema("FleetPoolCapProjection", { description: "One pool's label and cap in each phase." }));

/**
 * Decoded pool cap projection.
 *
 * @category models
 * @since 0.0.0
 */
export type FleetPoolCapProjection = typeof FleetPoolCapProjection.Type;

/**
 * The phase the fleet runs in and every pool's caps.
 *
 * **Example** (Read the projected phase)
 *
 * ```ts
 * import { projectFleetPoolCaps } from "@beep/infra-ci-runners/FleetPoolCaps"
 * import { productionConfig } from "@beep/infra-ci-runners/Config"
 *
 * console.log(projectFleetPoolCaps(productionConfig).phase) // "primary"
 * ```
 *
 * @category models
 * @since 0.0.0
 */
export const FleetPoolCapsProjection = S.Struct({
  phase: FleetPhase,
  pools: S.Array(FleetPoolCapProjection),
}).pipe($I.annoteSchema("FleetPoolCapsProjection", { description: "The fleet phase and every pool's caps." }));

/**
 * Decoded caps projection.
 *
 * @category models
 * @since 0.0.0
 */
export type FleetPoolCapsProjection = typeof FleetPoolCapsProjection.Type;

/**
 * The repository path of the generated module the check reads.
 *
 * **Example** (Read the generated path)
 *
 * ```ts
 * import { fleetPoolCapsGeneratedPath } from "@beep/infra-ci-runners/FleetPoolCaps"
 *
 * console.log(fleetPoolCapsGeneratedPath.endsWith(".generated.ts")) // true
 * ```
 *
 * @category configuration
 * @since 0.0.0
 */
export const fleetPoolCapsGeneratedPath = "packages/tooling/tool/cli/src/commands/Ci/FleetPoolCaps.generated.ts";

/**
 * Project a configuration's pools onto their labels and phase caps.
 *
 * **Example** (Read the production overflow cap)
 *
 * ```ts
 * import { projectFleetPoolCaps } from "@beep/infra-ci-runners/FleetPoolCaps"
 * import { productionConfig } from "@beep/infra-ci-runners/Config"
 *
 * console.log(projectFleetPoolCaps(productionConfig).pools[1]?.primary) // 48
 * ```
 *
 * @param config - The encoded stack configuration.
 * @returns The phase and each pool's label and caps.
 * @category configuration
 * @since 0.0.0
 */
export const projectFleetPoolCaps = (config: CiRunnersConfig.Encoded): FleetPoolCapsProjection => ({
  phase: config.phase,
  pools: A.map([config.heavy, config.overflow], (encoded) => {
    const pool = PoolSettings.make(encoded);
    return {
      pool: pool.name,
      label: pool.label,
      overlap: effectiveCap(pool, "overlap"),
      primary: effectiveCap(pool, "primary"),
    };
  }),
});

const poolLines = (pool: FleetPoolCapProjection): ReadonlyArray<string> => [
  "    {",
  `      pool: "${pool.pool}",`,
  `      label: "${pool.label}",`,
  `      overlap: ${pool.overlap},`,
  `      primary: ${pool.primary},`,
  "    },",
];

const projectionLines = (projection: FleetPoolCapsProjection): ReadonlyArray<string> => [
  "export const fleetPoolCapsProjection = {",
  `  phase: "${projection.phase}",`,
  "  pools: [",
  ...A.flatMap(projection.pools, poolLines),
  "  ],",
  "} as const;",
];

const moduleHeader = [
  "/**",
  " * Each runner pool's label and cap per phase, projected from `productionConfig`",
  " * in `packages/tooling/infra/ci-runners/src/Config.ts`.",
  " *",
  " * **Details**",
  " *",
  " * Generated by `bun packages/tooling/infra/ci-runners/fleet-pool-caps.ts --write`;",
  " * never edit it by hand. The infra package's `FleetPoolCaps` test fails when",
  " * this file differs from the production configuration.",
  " *",
  " * **Example** (Read the projected phase)",
  " *",
  " * ```ts",
  ' * import { fleetPoolCapsProjection } from "@beep/repo-cli/commands/Ci"',
  " *",
  ' * console.log(fleetPoolCapsProjection.phase) // "primary"',
  " * ```",
  " *",
  " * @category configuration",
  " * @since 0.0.0",
  " */",
];

/**
 * Render the generated module for a projection.
 *
 * **Example** (Render the production module)
 *
 * ```ts
 * import { projectFleetPoolCaps, renderFleetPoolCapsModule } from "@beep/infra-ci-runners/FleetPoolCaps"
 * import { productionConfig } from "@beep/infra-ci-runners/Config"
 *
 * const text = renderFleetPoolCapsModule(projectFleetPoolCaps(productionConfig))
 * console.log(text.includes("export const fleetPoolCapsProjection")) // true
 * ```
 *
 * @param projection - The caps to render.
 * @returns The module's full text, ending in a newline.
 * @category configuration
 * @since 0.0.0
 */
export const renderFleetPoolCapsModule = (projection: FleetPoolCapsProjection): string =>
  Str.concat(A.join(A.appendAll(moduleHeader, projectionLines(projection)), "\n"), "\n");

/**
 * The module text the production configuration renders to.
 *
 * **Example** (Compare against a committed copy)
 *
 * ```ts
 * import { productionFleetPoolCapsModule } from "@beep/infra-ci-runners/FleetPoolCaps"
 *
 * console.log(productionFleetPoolCapsModule().endsWith("\n")) // true
 * ```
 *
 * @returns The rendered module of {@link productionConfig}.
 * @category configuration
 * @since 0.0.0
 */
export const productionFleetPoolCapsModule = (): string =>
  renderFleetPoolCapsModule(projectFleetPoolCaps(productionConfig));
