type SchemaKindRule = {
  readonly kind: SchemaCatalogEntryKind;
  readonly matches: (calls: ReadonlyArray<CallExpression>, node: Node) => boolean;
};

// Ordered classification rules: the first matching rule wins, so the more
// specific declaration shapes stay ahead of the broad schema-const fallback.
const SCHEMA_KIND_RULES: ReadonlyArray<SchemaKindRule> = [
  {
    kind: "tagged-error",
    matches: (calls) => hasPropertyAccessCall(calls, "S", ["TaggedError"]),
  },
  { kind: "error-class", matches: (calls) => hasPropertyAccessCall(calls, "S", ["ErrorClass"]) },
  { kind: "tagged-class", matches: (calls) => hasPropertyAccessCall(calls, "S", ["TaggedClass"]) },
  {
    kind: "schema-class",
    matches: (calls) => hasPropertyAccessCall(calls, "S", ["Class"]) || hasProductEntityClassCall(calls),
  },
  { kind: "literal-kit", matches: (calls) => hasIdentifierCall(calls, ["LiteralKit", "MappedLiteralKit"]) },
  { kind: "tagged-union", matches: (calls) => hasPropertyAccessCall(calls, "S", ["TaggedUnion", "toTaggedUnion"]) },
  { kind: "union", matches: (calls) => hasPropertyAccessCall(calls, "S", ["Union"]) },
  { kind: "tagged-struct", matches: (calls) => hasPropertyAccessCall(calls, "S", ["TaggedStruct"]) },
  { kind: "struct-const", matches: (calls) => hasPropertyAccessCall(calls, "S", ["Struct"]) },
  { kind: "brand", matches: (calls) => hasPropertyAccessCall(calls, "S", ["brand", "fromBrand"]) },
  {
    kind: "codec",
    matches: (calls) =>
      hasPropertyAccessCall(calls, "S", ["decodeTo", "encodeTo", "fromJsonString"]) ||
      hasPropertyAccessCall(calls, "SchemaTransformation", SCHEMA_TRANSFORMATION_MEMBER_NAMES),
  },
  {
    kind: "schema-const",
    matches: (calls, node) =>
      hasPropertyAccessCall(calls, "S", SCHEMA_CONST_MEMBER_NAMES) || expressionStartsWithSchemaPrimitive(node),
  },
];

const schemaKindFromCalls = (calls: ReadonlyArray<CallExpression>, node: Node): O.Option<SchemaCatalogEntryKind> =>
  pipe(
    A.findFirst(SCHEMA_KIND_RULES, (rule) => rule.matches(calls, node)),
    O.map((rule) => rule.kind)
  );

const initializerFromIdentifier = (identifier: Identifier): O.Option<Expression> => {
  const declarations = identifier.getSymbol()?.getDeclarations() ?? A.empty<Node>();
  for (const declaration of declarations) {
    if (Node.isVariableDeclaration(declaration)) {
      return O.fromNullishOr(declaration.getInitializer());
    }
  }
  return O.none();
};

const pipeReceiverExpression = (expression: Expression): O.Option<Expression> => {
  if (!Node.isCallExpression(expression)) {
    return O.none();
  }
  const callTarget = expression.getExpression();
  if (!Node.isPropertyAccessExpression(callTarget) || !Str.Equivalence(callTarget.getName(), "pipe")) {
    return O.none();
  }
  return O.some(callTarget.getExpression());
};

const schemaKindFromExpression = (expression: Expression, depth = 0): O.Option<SchemaCatalogEntryKind> => {
  const directKind = schemaKindFromCalls(callExpressionsIn(expression), expression);
  if (O.isSome(directKind)) {
    return directKind;
  }
  if (depth > 2) {
    return O.none();
  }

  const receiver = pipeReceiverExpression(expression);
  if (O.isSome(receiver) && Node.isIdentifier(receiver.value)) {
    return pipe(
      initializerFromIdentifier(receiver.value),
      O.flatMap((initializer) => schemaKindFromExpression(initializer, depth + 1))
    );
  }

  if (Node.isIdentifier(expression)) {
    return pipe(
      initializerFromIdentifier(expression),
      O.flatMap((initializer) => schemaKindFromExpression(initializer, depth + 1))
    );
  }

  return O.none();
};

const propertyNameText = (property: PropertyAssignment): O.Option<string> => {
  const nameNode = property.getNameNode();
  if (Node.isIdentifier(nameNode)) {
    return O.some(nameNode.getText());
  }
  if (Node.isStringLiteral(nameNode)) {
    return O.some(nameNode.getLiteralText());
  }
  return O.none();
};

const descriptionFromAnnotationOptions = (optionsNode: Node | undefined): O.Option<string> => {
  if (!Node.isObjectLiteralExpression(optionsNode)) {
    return O.none();
  }

  for (const property of optionsNode.getProperties()) {
    if (!Node.isPropertyAssignment(property)) {
      continue;
    }
    const name = propertyNameText(property);
    if (O.isNone(name) || !Str.Equivalence(name.value, "description")) {
      continue;
    }
    return literalTextFromNode(property.getInitializer());
  }

  return O.none();
};

const isIdentityAnnotationCall = (callExpression: CallExpression): boolean => {
  const expression = callExpression.getExpression();
  return (
    Node.isPropertyAccessExpression(expression) &&
    Str.Equivalence(expression.getExpression().getText(), "$I") &&
    literalMemberEquals(["annote", "annoteSchema"], expression.getName())
  );
};

const enclosingCallCount =
  (root: Node) =>
  (node: Node): number =>
    pipe(
      node.getAncestors(),
      A.takeWhile((ancestor) => ancestor !== root),
      A.filter(Node.isCallExpression),
      A.length
    );

const byEnclosingCallCount = Order.mapInput(Order.Number, ({ depth }: { readonly depth: number }) => depth);

// The declaration's own annotation is its least-nested identity call: the outer `.pipe($I.annoteSchema(...))`
// or a class's trailing `$I.annote(...)`. Check arguments (`S.isPattern(re, $I.annote(...))`) and field
// schemas sit deeper, so they never name the declaration. Ties keep source order.
const metadataFromAnnotationCalls = (node: Node): SchemaCatalogMetadata =>
  pipe(
    callExpressionsIn(node),
    A.filter(isIdentityAnnotationCall),
    A.map((callExpression) => ({ callExpression, depth: enclosingCallCount(node)(callExpression) })),
    A.sort(byEnclosingCallCount),
    A.head,
    O.match({
      onNone: () => ({ identity: O.none<string>(), description: O.none<string>() }),
      onSome: ({ callExpression }) => {
        const args = callExpression.getArguments();
        return {
          identity: pipe(O.fromNullishOr(args[0]), O.flatMap(literalTextFromNode)),
          description: descriptionFromAnnotationOptions(args[1]),
        };
      },
    })
  );

const identityFromTaggedTemplate = (node: Node): O.Option<string> => {
  for (const expression of node.getDescendantsOfKind(SyntaxKind.TaggedTemplateExpression)) {
    if (!Str.Equivalence(expression.getTag().getText(), "$I")) {
      continue;
    }
    const template = expression.getTemplate();
    if (Node.isNoSubstitutionTemplateLiteral(template)) {
      return O.some(template.getLiteralValue());
    }
  }
  return O.none();
};

const metadataFromNode = (node: Node): SchemaCatalogMetadata => {
  const fromAnnotation = metadataFromAnnotationCalls(node);
  return {
    identity: pipe(
      fromAnnotation.identity,
      O.orElse(() => identityFromTaggedTemplate(node))
    ),
    description: fromAnnotation.description,
  };
};

const makeCatalogEntry = (
  file: string,
  symbol: string,
  kind: SchemaCatalogEntryKind,
  owner: string,
  node: Node
): SchemaCatalogEntry => {
  const metadata = metadataFromNode(node);
  return SchemaCatalogEntry.make({
    file,
    symbol,
    kind,
    owner,
    ...optionalProp("identity", metadata.identity),
    ...optionalProp("description", metadata.description),
  });
};

const catalogEntryFromClassDeclaration = (
  declaration: ClassDeclaration,
  file: string,
  owner: string
): O.Option<SchemaCatalogEntry> => {
  // The catalog is the exported crispened surface; private helper schemas
  // (module-local bases, internal codecs) stay out of it.
  if (!declaration.isExported()) {
    return O.none();
  }
  const symbol = declaration.getName();
  const heritageExpression = declaration.getExtends()?.getExpression();
  if (symbol === undefined || heritageExpression === undefined) {
    return O.none();
  }

  return pipe(
    schemaKindFromExpression(heritageExpression),
    O.map((kind) => makeCatalogEntry(file, symbol, kind, owner, declaration))
  );
};

const catalogEntryFromVariableDeclaration = (
  declaration: VariableDeclaration,
  file: string,
  owner: string
): O.Option<SchemaCatalogEntry> =>
  pipe(
    O.fromNullishOr(declaration.getInitializer()),
    O.filter((initializer) => !Node.isArrowFunction(initializer) && !Node.isFunctionExpression(initializer)),
    O.flatMap((initializer) =>
      pipe(
        schemaKindFromExpression(initializer),
        O.map((kind) => makeCatalogEntry(file, declaration.getName(), kind, owner, initializer))
      )
    )
  );

const collectCatalogEntriesFromSourceFile = (
  sourceFile: SourceFile,
  file: string,
  owner: string
): ReadonlyArray<SchemaCatalogEntry> => {
  const entries = A.empty<SchemaCatalogEntry>();

  for (const declaration of sourceFile.getClasses()) {
    const entry = catalogEntryFromClassDeclaration(declaration, file, owner);
    if (O.isSome(entry)) {
      A.appendInPlace(entries, entry.value);
    }
  }

  for (const variableStatement of sourceFile.getVariableStatements()) {
    if (!variableStatement.isExported()) {
      continue;
    }
    for (const declaration of variableStatement.getDeclarations()) {
      const entry = catalogEntryFromVariableDeclaration(declaration, file, owner);
      if (O.isSome(entry)) {
        A.appendInPlace(entries, entry.value);
      }
    }
  }

  return entries;
};

/**
 * Generate the static schema catalog document from the schema-first scan scope.
 *
 * **Details**
 *
 * `globs` narrows the scan to a subset of the schema-first source globs; a
 * scoped run passes the owning packages' directories so the document holds
 * exactly their entries. Omitted, the whole scan scope is read.
 *
 * **Example** (Wrap document generator Effect)
 *
 * ```ts
 * import { generateSchemaCatalogDocument } from "@beep/repo-cli/commands/Lint"
 * import * as Effect from "effect/Effect";
 * const program = Effect.succeed(generateSchemaCatalogDocument)
 * console.log(Effect.isEffect(program)) // true
 * ```
 *
 * @category use-cases
 * @since 0.0.0
 */
export const generateSchemaCatalogDocument = Effect.fn("SchemaCatalog.generateDocument")(function* (
  globs: ReadonlyArray<string> = SchemaFirstIncludedGlobs
) {
  return yield* Effect.gen(function* () {
    const path = yield* Path.Path;
    const fsUtils = yield* FsUtils;
    const repoRoot = yield* findRepoRoot();
    const ownerResolver = yield* makeSchemaFirstOwnerResolver(repoRoot);
    // Enumerate through FsUtils so the scan is anchored at the repo root even
    // when the command runs from a workspace subdirectory (ts-morph resolves
    // relative globs against the process cwd).
    const sourcePaths = yield* fsUtils.globFiles(
      globs,
      GlobOptions.make({
        absolute: true,
        cwd: repoRoot,
        ignore: "**/docs/**",
      })
    );
    const project = new Project({
      skipAddingFilesFromTsConfig: true,
      tsConfigFilePath: path.join(repoRoot, "tsconfig.json"),
    });
    for (const sourcePath of sourcePaths) {
      project.addSourceFileAtPath(sourcePath);
    }
    const entries = A.empty<SchemaCatalogEntry>();

    for (const sourceFile of project.getSourceFiles()) {
      const filePath = toPosixPath(path.relative(repoRoot, sourceFile.getFilePath()));
      if (isExcludedFile(filePath)) {
        continue;
      }
      const owner = ownerResolver(sourceFile.getFilePath());
      A.appendAllInPlace(entries, collectCatalogEntriesFromSourceFile(sourceFile, filePath, owner));
    }

    return SchemaCatalogDocument.make({
      schemaVersion: "schema-catalog/v1",
      generatedBy: SCHEMA_CATALOG_GENERATED_BY,
      entries: sortCatalogEntries(A.dedupeWith(entries, (left, right) => makeEntryKey(left) === makeEntryKey(right))),
    });
  }).pipe(Effect.withSpan("SchemaCatalog.generateDocument"));
});

/**
 * Repo-relative path of one owner's schema catalog shard.
 *
 * **Example** (Locate a shard)
 *
 * ```ts
 * import { schemaCatalogShardPath } from "@beep/repo-cli/commands/Lint"
 *
 * console.log(schemaCatalogShardPath("@beep/schema")) // "standards/schema-catalog/@beep/schema.generated.jsonc"
 * ```
 *
 * @param owner - Scoped package name that owns the shard.
 * @returns The shard path, keeping the package scope as a folder.
 * @category formatting
 * @since 0.0.0
 */
export const schemaCatalogShardPath = (owner: string): string =>
  `${SCHEMA_CATALOG_DIR}/${owner}${SCHEMA_CATALOG_SHARD_SUFFIX}`;

/**
 * Split the whole schema catalog into one shard per owning package, sorted by
 * owner.
 *
 * **Details**
 *
 * Fails when an owner is not a scoped package name, because the owner names
 * the shard file.
 *
 * **Example** (Wrap the sharding Effect)
 *
 * ```ts
 * import { SchemaCatalogDocument, shardSchemaCatalogDocument } from "@beep/repo-cli/commands/Lint"
 * import * as Effect from "effect/Effect"
 *
 * const document = SchemaCatalogDocument.make({
 *   schemaVersion: "schema-catalog/v1",
 *   generatedBy: "bun run beep lint schema-catalog --write",
 *   entries: []
 * })
 * console.log(Effect.runSync(shardSchemaCatalogDocument(document)).length) // 0
 * ```
 *
 * @category mapping
 * @since 0.0.0
 */
export const shardSchemaCatalogDocument = Effect.fn("SchemaCatalog.shardDocument")(function* (
  document: SchemaCatalogDocument
) {
  const groups = A.groupBy(document.entries, (entry) => entry.owner);
  return yield* Effect.forEach(A.sort(R.keys(groups), Order.String), (owner) =>
    decodeSchemaCatalogShard({
      schemaVersion: "schema-catalog-shard/v1",
      generatedBy: SCHEMA_CATALOG_GENERATED_BY,
      owner,
      entries: O.getOrElse(R.get(groups, owner), A.empty),
    })
  );
});

/**
 * Render one schema catalog shard as deterministic JSONC, one entry per line.
 *
 * **Example** (Wrap the shard renderer)
 *
 * ```ts
 * import { renderSchemaCatalogShard } from "@beep/repo-cli/commands/Lint"
 * import * as Effect from "effect/Effect"
 * const program = Effect.succeed(renderSchemaCatalogShard)
 * console.log(Effect.isEffect(program)) // true
 * ```
 *
 * @category formatting
 * @since 0.0.0
 */
export const renderSchemaCatalogShard = Effect.fn("SchemaCatalog.renderShard")(function* (shard: SchemaCatalogShard) {
  const encoded = yield* encodeSchemaCatalogShard(shard);
  const json = Effect.fn(function* (value: unknown) {
    const rendered = yield* SchemaGetter.run(stringifyJsonCompact, O.some(value), {});
    return O.getOrElse(rendered, thunkEmptyStr);
  });
  const header = yield* Effect.forEach(
    [
      ["schemaVersion", encoded.schemaVersion],
      ["generatedBy", encoded.generatedBy],
      ["owner", encoded.owner],
    ] as const,
    ([key, value]) => Effect.map(json(value), (text) => `  "${key}": ${text}`)
  );
  const lines = yield* Effect.forEach(encoded.entries, json);
  const entries = A.isReadonlyArrayEmpty(lines)
    ? `  "entries": []`
    : `  "entries": [\n${A.join(
        A.map(lines, (line) => `    ${line}`),
        ",\n"
      )}\n  ]`;
  return `${SCHEMA_CATALOG_HEADER}\n{\n${A.join([...header, entries], ",\n")}\n}\n`;
});

/**
 * Generate the committed schema catalog: every shard's repo-relative path and
 * deterministic JSONC text.
 *
 * **Example** (Wrap the shard generator)
 *
 * ```ts
 * import { generateSchemaCatalogShards } from "@beep/repo-cli/commands/Lint"
 * import * as Effect from "effect/Effect";
 * const program = Effect.succeed(generateSchemaCatalogShards)
 * console.log(Effect.isEffect(program)) // true
 * ```
 *
 * @category use-cases
 * @since 0.0.0
 */
export const generateSchemaCatalogShards = Effect.fn("SchemaCatalog.generateShards")(function* (
  document: SchemaCatalogDocument
) {
  const shards = yield* shardSchemaCatalogDocument(document);
  return yield* Effect.forEach(shards, (shard) =>
    Effect.map(renderSchemaCatalogShard(shard), (content) => ({
      path: schemaCatalogShardPath(shard.owner),
      content,
    }))
  );
});

const existingCatalogFiles = Effect.fn("SchemaCatalog.existingFiles")(function* (repoRoot: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const fsUtils = yield* FsUtils;
  const shards = yield* fsUtils.globFiles(
    [`${SCHEMA_CATALOG_DIR}/**/*${SCHEMA_CATALOG_SHARD_SUFFIX}`],
    GlobOptions.make({ absolute: true, cwd: repoRoot })
  );
  const retired = yield* fs.exists(path.join(repoRoot, RETIRED_SCHEMA_CATALOG_PATH));
  return A.sort(
    [
      ...A.map(shards, (file) => toPosixPath(path.relative(repoRoot, file))),
      ...(retired ? [RETIRED_SCHEMA_CATALOG_PATH] : []),
    ],
    Order.String
  );
});

const syncShard = Effect.fn("SchemaCatalog.syncShard")(function* (
  write: boolean,
  repoRoot: string,
  shard: { readonly path: string; readonly content: string }
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const absolute = path.join(repoRoot, shard.path);
  const current = (yield* fs.exists(absolute)) ? O.some(yield* fs.readFileString(absolute)) : O.none<string>();
  if (O.contains(current, shard.content)) {
    return O.none<ShardDrift>();
  }
  if (!write) {
    return O.some(drift(shard.path, O.isSome(current) ? "stale" : "missing"));
  }
  yield* fs.makeDirectory(path.dirname(absolute), { recursive: true });
  yield* fs.writeFileString(absolute, shard.content);
  return O.some(drift(shard.path, "wrote"));
});

const retireFile = Effect.fn("SchemaCatalog.retireFile")(function* (write: boolean, repoRoot: string, file: string) {
  if (!write) {
    return O.some(drift(file, "orphaned"));
  }
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  yield* fs.remove(path.join(repoRoot, file));
  return O.some(drift(file, "removed"));
});

type ShardDrift = { readonly path: string; readonly line: string };

const drift = (path: string, status: string): ShardDrift => ({ path, line: `[schema-catalog] ${status} ${path}` });

const reportDrift = Effect.fn("SchemaCatalog.reportDrift")(function* (
  write: boolean,
  drifted: ReadonlyArray<ShardDrift>,
  scopeLabel: string
) {
  const lines = A.map(drifted, (entry) => entry.line);
  if (!write && A.isReadonlyArrayNonEmpty(lines)) {
    yield* Effect.forEach(lines, (line) => Console.error(line), { discard: true });
    return yield* failWithReportedExit(
      `schema-catalog: ${A.length(lines)} shard(s) under ${SCHEMA_CATALOG_DIR} are stale, missing or orphaned; run ${SCHEMA_CATALOG_GENERATED_BY}.`
    );
  }
  yield* Effect.forEach(lines, (line) => Console.log(line), { discard: true });
  yield* Console.log(write ? `[schema-catalog] wrote ${scopeLabel}` : `[schema-catalog] ${scopeLabel} is current`);
});

// Shared tail of the full and scoped runs: stage what a write changed, then summarize.
const finishSchemaCatalogRun = Effect.fn("SchemaCatalog.finishRun")(function* (
  options: SchemaCatalogOptions,
  repoRoot: string,
  document: SchemaCatalogDocument,
  shards: ReadonlyArray<{ readonly path: string; readonly content: string }>,
  drifted: ReadonlyArray<ShardDrift>
) {
  const changed = options.write ? A.map(drifted, (entry) => entry.path) : A.empty<string>();
  if (options.stage) {
    yield* stageGeneratedFiles(repoRoot, changed);
  }
  const summary = SchemaCatalogSummary.make({
    entries: A.length(document.entries),
    shards: A.length(shards),
    wroteCatalog: options.write,
    changed,
  });
  yield* Console.log(`[schema-catalog] entries=${summary.entries} shards=${summary.shards}`);
  return summary;
});

// The `infra/` tree is not a workspace member, so the owner resolver's prefix
// fallback names it; its scoped globs are the schema-first ones verbatim so a
// scoped shard matches the full scan byte for byte.
const INFRA_SCOPE_OWNER = ShardScopeOwner.make({
  owner: "@beep/infra",
  globs: A.filter(SchemaFirstIncludedGlobs, Str.startsWith("infra/")),
});

const scopedGlobsForDirectory = (directory: string): ReadonlyArray<string> => [`${directory}/**/*.{ts,tsx}`];

/**
 * Regenerate only the shards owned by the packages that own `paths`.
 *
 * **Details**
 *
 * The scan reads just those packages' sources, so the run costs seconds, not
 * the half minute of a repository-wide scan, and the resulting shard text is
 * the same the full scan would write because entries never cross packages.
 * Orphan retirement outside the scope and the retired single-file catalog are
 * left to the full run; an in-scope owner that lost its last schema has its
 * shard removed.
 */
const runScopedSchemaCatalog = Effect.fn("SchemaCatalog.runScoped")(function* (
  options: SchemaCatalogOptions,
  repoRoot: string
) {
  const ownerResolver = yield* makeSchemaFirstOwnerResolver(repoRoot);
  const scope = yield* resolveShardScope({
    repoRoot,
    paths: options.paths,
    ownerOf: ownerResolver,
    globsForDirectory: scopedGlobsForDirectory,
    fallbackOwners: [INFRA_SCOPE_OWNER],
  });
  const owners = A.map(scope.owners, (owner) => owner.owner);
  if (A.isReadonlyArrayEmpty(owners)) {
    yield* Console.log(`[schema-catalog] no owning package for the given paths; nothing to regenerate`);
    return SchemaCatalogSummary.make({ entries: 0, shards: 0, wroteCatalog: options.write, changed: [] });
  }
  const document = yield* generateSchemaCatalogDocument(A.flatMap(scope.owners, (owner) => owner.globs));
  const shards = A.filter(yield* generateSchemaCatalogShards(document), (shard) =>
    A.some(owners, (owner) => shard.path === schemaCatalogShardPath(owner))
  );
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const emptied = yield* Effect.filter(
    A.filter(A.map(owners, schemaCatalogShardPath), (file) => !A.some(shards, (shard) => shard.path === file)),
    (file) => fs.exists(path.join(repoRoot, file))
  );
  const drifted = A.getSomes([
    ...(yield* Effect.forEach(shards, (shard) => syncShard(options.write, repoRoot, shard))),
    ...(yield* Effect.forEach(emptied, (file) => retireFile(options.write, repoRoot, file))),
  ]);
  yield* reportDrift(options.write, drifted, A.join(owners, ", "));
  return yield* finishSchemaCatalogRun(options, repoRoot, document, shards, drifted);
});

/**
 * Run schema catalog write/check mode.
 *
 * **Details**
 *
 * Write mode rewrites only shards whose text changed and deletes shards no
 * package owns any more, including the retired single-file catalog. Check
 * mode reports every stale, missing or orphaned shard and fails when any
 * exists. With `paths`, only the shards of the packages owning those paths
 * are generated and compared; with `stage`, a write run adds the shards it
 * changed to the git index.
 *
 * **Example** (Wrap catalog runner Effect)
 *
 * ```ts
 * import { runSchemaCatalog } from "@beep/repo-cli/commands/Lint"
 * import * as Effect from "effect/Effect";
 * const program = Effect.succeed(runSchemaCatalog)
 * console.log(Effect.isEffect(program)) // true
 * ```
 *
 * @category use-cases
 * @since 0.0.0
 */
export const runSchemaCatalog = Effect.fn("SchemaCatalog.run")(function* (options: SchemaCatalogOptions) {
  return yield* Effect.gen(function* () {
    const repoRoot = yield* findRepoRoot();
    if (A.isReadonlyArrayNonEmpty(options.paths)) {
      return yield* runScopedSchemaCatalog(options, repoRoot);
    }
    const document = yield* generateSchemaCatalogDocument();
    const shards = yield* generateSchemaCatalogShards(document);
    const expected = A.map(shards, (shard) => shard.path);
    const orphans = A.filter(yield* existingCatalogFiles(repoRoot), (file) => !A.contains(expected, file));
    const drifted = A.getSomes([
      ...(yield* Effect.forEach(shards, (shard) => syncShard(options.write, repoRoot, shard))),
      ...(yield* Effect.forEach(orphans, (file) => retireFile(options.write, repoRoot, file))),
    ]);
    yield* reportDrift(options.write, drifted, SCHEMA_CATALOG_DIR);
    return yield* finishSchemaCatalogRun(options, repoRoot, document, shards, drifted);
  }).pipe(Effect.withSpan("SchemaCatalog.run"));
});

