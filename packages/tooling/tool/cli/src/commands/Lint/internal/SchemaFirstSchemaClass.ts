/**
 * Schema-class shape detectors for the branded `S.Opaque` default (goal
 * `schema-opaque-default`, decisions D1-D4 and D8).
 *
 * @packageDocumentation
 * @since 0.0.0
 */

import { $RepoCliId } from "@beep/identity/packages";
import { LiteralKit } from "@beep/schema";
import { A, Str } from "@beep/utils";
import { pipe } from "effect/Function";
import * as HashSet from "effect/HashSet";
import * as O from "effect/Option";
import * as S from "effect/Schema";
import { ts } from "ts-morph";
import { SchemaFirstInventoryEntry } from "../Lint.schemas.ts";

const $I = $RepoCliId.create("commands/Lint/internal/SchemaFirstSchemaClass");

const DEFAULT_SCHEMA_NAMESPACES = ["S"] as const;
const GENERATED_HEADER_PATTERN =
  /(@generated|auto-?generated|this file (is|was) (auto-?)?generated|code generated|generated by|do not edit)/i;
const LEADING_COMMENT_BLOCK_PATTERN = /^(\s*(\/\/[^\n]*\n|\/\*[\s\S]*?\*\/))+/;
const IDENTITY_ANNOTATION_PATTERN = /\$I\.annote(?:Schema)?\(/;
const SCHEMA_MODULE_SPECIFIER_PATTERN = /\/Schema(?:\.ts)?$/;
const DECLARATION_HOOK_KEY_PATTERN = /^to[A-Z]/;

/**
 * Schema constructors whose `class X extends <ns>.<Kind><Self, Brand>(...)(...)`
 * heritage the detectors recognise.
 *
 * **Example** (Check a schema class kind)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 * import * as S from "effect/Schema"
 *
 * console.log(S.is(SchemaFirstSchemaClass.SchemaClassKind)("Opaque")) // true
 * ```
 *
 * @category schema
 * @since 0.0.0
 */
const SchemaClassKind = LiteralKit(["Class", "TaggedClass", "Error", "TaggedError", "Opaque"]).pipe(
  $I.annoteSchema("SchemaClassKind", {
    description: "Schema constructor named by a schema class declaration's heritage.",
  })
);

/**
 * Schema constructor named by a schema class declaration's heritage.
 *
 * **Example** (Type a schema class kind)
 *
 * ```ts
 * import type { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * const kind: typeof SchemaFirstSchemaClass.SchemaClassKind.Type = "TaggedClass"
 * console.log(kind) // "TaggedClass"
 * ```
 *
 * @category type-level
 * @since 0.0.0
 */
type SchemaClassKind = typeof SchemaClassKind.Type;

const isSchemaClassKind = S.is(SchemaClassKind);

/**
 * Brand carried by a schema class declaration's second type argument.
 *
 * **Details**
 *
 * `missing` means no brand type argument (the constructor defaults it to `{}`),
 * `structural` an explicit empty `{}` type literal, and `nominal` any other
 * brand, such as `{ readonly brand: unique symbol }`.
 *
 * **Example** (Check a brand state)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 * import * as S from "effect/Schema"
 *
 * console.log(S.is(SchemaFirstSchemaClass.SchemaClassBrand)("structural")) // true
 * ```
 *
 * @category schema
 * @since 0.0.0
 */
const SchemaClassBrand = LiteralKit(["missing", "structural", "nominal"]).pipe(
  $I.annoteSchema("SchemaClassBrand", {
    description: "Brand carried by a schema class declaration's second type argument.",
  })
);

/**
 * Brand state of a schema class declaration.
 *
 * **Example** (Type a brand state)
 *
 * ```ts
 * import type { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * const brand: typeof SchemaFirstSchemaClass.SchemaClassBrand.Type = "nominal"
 * console.log(brand) // "nominal"
 * ```
 *
 * @category type-level
 * @since 0.0.0
 */
type SchemaClassBrand = typeof SchemaClassBrand.Type;

/**
 * Syntactic facts about one schema class declaration in a source file.
 *
 * **Example** (Build declaration facts)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * const facts = SchemaFirstSchemaClass.SchemaClassDeclaration.make({
 *   symbol: "Point",
 *   kind: "Class",
 *   brandState: "missing",
 *   line: 3,
 *   offset: 40,
 *   hasInstanceMembers: false,
 *   hasIdentityTemplate: true,
 *   hasIdentityAnnotation: true,
 *   hasInlineSource: true,
 *   hasDeclarationHooks: false,
 * })
 * console.log(facts.brandState) // "missing"
 * ```
 *
 * @category models
 * @since 0.0.0
 */
export class SchemaClassDeclaration extends S.Opaque<SchemaClassDeclaration, { readonly brand: unique symbol }>()(
  S.Struct({
    symbol: S.String,
    kind: SchemaClassKind,
    brandState: SchemaClassBrand,
    line: S.Finite,
    offset: S.Finite,
    hasInstanceMembers: S.Boolean,
    hasIdentityTemplate: S.Boolean,
    hasIdentityAnnotation: S.Boolean,
    hasInlineSource: S.Boolean,
    hasDeclarationHooks: S.Boolean,
  }).pipe(
    $I.annoteSchema("SchemaClassDeclaration", {
      description: "Syntactic facts about one schema class declaration in a source file.",
    })
  )
) {}

/**
 * Schema class declarations of one source file plus the class names it
 * references through `.extend`, subclassing, `instanceof`, `new` or
 * `S.instanceOf`.
 *
 * **Example** (Build an empty scan result)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * const scan = SchemaFirstSchemaClass.SchemaClassSourceScan.make({ declarations: [], referencedNames: [] })
 * console.log(scan.declarations.length) // 0
 * ```
 *
 * @category models
 * @since 0.0.0
 */
class SchemaClassSourceScan extends S.Opaque<SchemaClassSourceScan, { readonly brand: unique symbol }>()(
  S.Struct({
    declarations: S.Array(SchemaClassDeclaration),
    referencedNames: S.Array(S.String),
  }).pipe(
    $I.annoteSchema("SchemaClassSourceScan", {
      description: "Schema class declarations of a source file and the class names it references.",
    })
  )
) {}

const lineOf = (sourceFile: ts.SourceFile, position: number): number =>
  sourceFile.getLineAndCharacterOfPosition(position).line + 1;

const isSchemaModuleSpecifier = (specifier: string): boolean =>
  specifier === "effect/Schema" || SCHEMA_MODULE_SPECIFIER_PATTERN.test(specifier);

const importedSchemaNamespaces = (statement: ts.Statement): ReadonlyArray<string> => {
  if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) return A.empty();
  const specifier = statement.moduleSpecifier.text;
  const bindings = statement.importClause?.namedBindings;
  if (bindings === undefined) return A.empty();
  if (ts.isNamespaceImport(bindings)) {
    return isSchemaModuleSpecifier(specifier) ? A.of(bindings.name.text) : A.empty();
  }
  return specifier === "effect"
    ? pipe(
        bindings.elements,
        A.filter((element) => (element.propertyName ?? element.name).text === "Schema"),
        A.map((element) => element.name.text)
      )
    : A.empty();
};

const schemaNamespacesOf = (sourceFile: ts.SourceFile): HashSet.HashSet<string> =>
  HashSet.fromIterable([...DEFAULT_SCHEMA_NAMESPACES, ...A.flatMap(sourceFile.statements, importedSchemaNamespaces)]);

const hasStaticModifier = (member: ts.ClassElement): boolean =>
  A.some(
    ts.canHaveModifiers(member) ? (ts.getModifiers(member) ?? []) : [],
    (modifier) => modifier.kind === ts.SyntaxKind.StaticKeyword
  );

const isInstanceMember = (member: ts.ClassElement): boolean => {
  if (ts.isSemicolonClassElement(member) || ts.isClassStaticBlockDeclaration(member)) return false;
  return ts.isConstructorDeclaration(member) || ts.isIndexSignatureDeclaration(member) || !hasStaticModifier(member);
};

const extendsExpression = (declaration: ts.ClassLikeDeclaration): O.Option<ts.Expression> =>
  pipe(
    A.findFirst(declaration.heritageClauses ?? [], (clause) => clause.token === ts.SyntaxKind.ExtendsKeyword),
    O.flatMap((clause) => A.head(clause.types)),
    O.map((type) => type.expression)
  );

const referencedName = (expression: ts.Expression): O.Option<string> => {
  if (ts.isIdentifier(expression)) return O.some(expression.text);
  return ts.isPropertyAccessExpression(expression) && ts.isIdentifier(expression.name)
    ? O.some(expression.name.text)
    : O.none();
};

const brandOf = (typeArguments: ReadonlyArray<ts.TypeNode>): SchemaClassBrand =>
  pipe(
    A.get(typeArguments, 1),
    O.match({
      onNone: () => "missing" as const,
      onSome: (brand) => (ts.isTypeLiteralNode(brand) && brand.members.length === 0 ? "structural" : "nominal"),
    })
  );

const isIdentityTemplate = (argument: ts.Expression | undefined): boolean =>
  argument !== undefined && ts.isTaggedTemplateExpression(argument) && argument.tag.getText() === "$I";

const objectHasDeclarationHook = (expression: ts.Expression): boolean =>
  ts.isObjectLiteralExpression(expression) &&
  A.some(
    expression.properties,
    (property) =>
      property.name !== undefined &&
      (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
      DECLARATION_HOOK_KEY_PATTERN.test(property.name.text)
  );

// Class-level `to*` Declaration hooks (`toCodecArbitrary`, `toEquivalence`, ...) passed inline or through
// `$I.annote(name, { ... })` in the annotations argument; an S.Opaque cannot carry them on a class Declaration.
const hasDeclarationHooks = (kind: SchemaClassKind, heritage: ts.CallExpression): boolean =>
  A.some(A.drop(heritage.arguments, kind === "TaggedClass" || kind === "TaggedError" ? 2 : 1), (argument) =>
    ts.isCallExpression(argument)
      ? A.some(argument.arguments, objectHasDeclarationHook)
      : objectHasDeclarationHook(argument)
  );

const isReferenceArgument = (argument: ts.Expression | undefined): boolean =>
  argument !== undefined && (ts.isIdentifier(argument) || ts.isPropertyAccessExpression(argument));

const schemaClassDeclaration = (
  sourceFile: ts.SourceFile,
  namespaces: HashSet.HashSet<string>,
  declaration: ts.ClassLikeDeclaration,
  heritage: ts.Expression
): O.Option<SchemaClassDeclaration> => {
  if (!ts.isCallExpression(heritage) || !ts.isCallExpression(heritage.expression)) return O.none();
  const inner = heritage.expression;
  const callee = inner.expression;
  if (!ts.isPropertyAccessExpression(callee) || !HashSet.has(namespaces, callee.expression.getText(sourceFile))) {
    return O.none();
  }
  const kind = callee.name.text;
  if (!isSchemaClassKind(kind)) return O.none();
  const line = lineOf(sourceFile, declaration.getStart(sourceFile));
  return O.some(
    SchemaClassDeclaration.make({
      symbol: declaration.name?.text ?? `<anonymous>@${line}`,
      kind,
      brandState: brandOf(inner.typeArguments ?? []),
      line,
      offset: callee.getStart(sourceFile),
      hasInstanceMembers: A.some(declaration.members, isInstanceMember),
      hasIdentityTemplate: isIdentityTemplate(inner.arguments[0]),
      hasIdentityAnnotation: IDENTITY_ANNOTATION_PATTERN.test(heritage.getText(sourceFile)),
      hasInlineSource: !isReferenceArgument(heritage.arguments[0]),
      hasDeclarationHooks: hasDeclarationHooks(kind, heritage),
    })
  );
};

// `class Y extends X` subclasses X; `class Y extends X.extend<Y>(...)(...)` is collected from the `.extend` access.
const subclassReference = (heritage: ts.Expression): O.Option<string> =>
  ts.isCallExpression(heritage) ? O.none() : referencedName(heritage);

// `X.extend<Y>(...)` names its root X only when the `.extend` access is the callee.
const extendRootReference = (node: ts.Node): O.Option<string> =>
  ts.isPropertyAccessExpression(node) &&
  node.name.text === "extend" &&
  ts.isCallExpression(node.parent) &&
  node.parent.expression === node
    ? referencedName(node.expression)
    : O.none();

const instanceOfOperatorReference = (node: ts.Node): O.Option<string> =>
  ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.InstanceOfKeyword
    ? referencedName(node.right)
    : O.none();

const newTargetReference = (node: ts.Node): O.Option<string> =>
  ts.isNewExpression(node) ? referencedName(node.expression) : O.none();

const schemaInstanceOfReference = (node: ts.Node): O.Option<string> =>
  ts.isCallExpression(node) &&
  ts.isPropertyAccessExpression(node.expression) &&
  node.expression.name.text === "instanceOf"
    ? pipe(O.fromUndefinedOr(node.arguments[0]), O.flatMap(referencedName))
    : O.none();

// The four reference shapes match disjoint node kinds, so the first Some is the only candidate.
const nodeReference = (node: ts.Node): O.Option<string> =>
  pipe(
    extendRootReference(node),
    O.orElse(() => instanceOfOperatorReference(node)),
    O.orElse(() => newTargetReference(node)),
    O.orElse(() => schemaInstanceOfReference(node))
  );

/**
 * Collect the schema class declarations of a parsed source file and the class
 * names it references as `.extend` roots, base classes, `instanceof` / `new`
 * targets or `S.instanceOf` arguments.
 *
 * **Details**
 *
 * The schema namespace is `S` plus every local name bound to `effect/Schema`
 * (namespace import, or `Schema` imported from `effect`). Only the
 * `<ns>.<Kind><Self, Brand>(...)(...)` heritage shape is a schema class
 * declaration; `X.extend<Y>()(...)` subclasses are references, not declarations.
 *
 * **Example** (Scan a source file)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 * import { ts } from "ts-morph"
 *
 * const sourceFile = ts.createSourceFile(
 *   "fixture.ts",
 *   'class Point extends S.Class<Point>("Point")({ x: S.Number }) {}\nconst bad = value instanceof Point',
 *   ts.ScriptTarget.Latest,
 *   true
 * )
 * const scan = SchemaFirstSchemaClass.scanSourceFile(sourceFile)
 * console.log(scan.declarations[0]?.brandState, scan.referencedNames) // "missing" ["Point"]
 * ```
 *
 * @param sourceFile - A TypeScript source file parsed with parent pointers.
 * @returns The declarations in source order and the referenced class names.
 * @category utilities
 * @since 0.0.0
 */
const scanSourceFile = (sourceFile: ts.SourceFile): SchemaClassSourceScan => {
  const namespaces = schemaNamespacesOf(sourceFile);
  const declarations = A.empty<SchemaClassDeclaration>();
  const referencedNames = A.empty<string>();
  const visit = (node: ts.Node): void => {
    if (ts.isClassDeclaration(node) || ts.isClassExpression(node)) {
      const declaration = node;
      O.map(extendsExpression(declaration), (heritage) => {
        const found = schemaClassDeclaration(sourceFile, namespaces, declaration, heritage);
        if (O.isSome(found)) {
          A.appendInPlace(declarations, found.value);
        } else {
          O.map(subclassReference(heritage), (name) => A.appendInPlace(referencedNames, name));
        }
      });
    } else {
      O.map(nodeReference(node), (name) => A.appendInPlace(referencedNames, name));
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return SchemaClassSourceScan.make({ declarations, referencedNames });
};

/**
 * True when the leading comment block of a source text marks it as generated.
 *
 * **Details**
 *
 * Mirrors the codemod's generated-file rule: only the comments before the
 * first statement, within the first 800 characters, are inspected.
 *
 * **Example** (Detect a generated header)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * console.log(SchemaFirstSchemaClass.isGeneratedSourceText("// @generated\nexport {}\n")) // true
 * ```
 *
 * @param text - Full source text.
 * @returns `true` when the leading comments carry a generated-file marker.
 * @category predicates
 * @since 0.0.0
 */
const isGeneratedSourceText = (text: string): boolean =>
  pipe(
    O.fromNullishOr(LEADING_COMMENT_BLOCK_PATTERN.exec(Str.slice(0, 800)(text))),
    O.flatMap(A.head),
    O.exists((leading) => GENERATED_HEADER_PATTERN.test(leading))
  );

// Every S.Class / S.TaggedClass / S.Error / S.TaggedError / S.Opaque declaration carries a nominal brand such as
// `{ readonly brand: unique symbol }` (D4). A missing brand argument or an explicit structural `{}` brand is a
// candidate until the inventory records a schema-first exception for it.
const unbrandedEntry = (
  declaration: SchemaClassDeclaration,
  file: string,
  owner: string
): O.Option<SchemaFirstInventoryEntry> =>
  declaration.brandState === "nominal"
    ? O.none()
    : O.some(
        SchemaFirstInventoryEntry.make({
          file,
          symbol: declaration.symbol,
          kind: "unbranded-schema-class",
          status: "candidate",
          reason:
            declaration.brandState === "missing"
              ? `S.${declaration.kind} declaration has no brand type argument; add { readonly brand: unique symbol } (D4).`
              : `S.${declaration.kind} declaration carries the structural {} brand; use { readonly brand: unique symbol } or record a schema-first exception (D4).`,
          owner,
        })
      );

// Plain-data heuristic (D1, D3): in-file facts plus a project-wide name index. A declaration is a candidate when it
// is an S.Class or S.TaggedClass (errors use S.Error/S.TaggedError and entities their own kits, so neither matches),
// its body has no instance members (statics are allowed), its annotations carry no class-level `to*` Declaration
// hooks, and its name is not in `referencedNames`: no project file (tests included) uses it as an `.extend` root,
// base class, `instanceof` / `new` target or `S.instanceOf` argument. The name index is conservative: a same-named
// class anywhere suppresses the finding. Classes that stay classes for reasons the scan cannot see (the codemod's
// keep-class allowlist, cross-file fields expressions, non-literal `_tag` fields) are inventory exceptions. Callers
// skip generated files.
const plainDataEntry = (
  declaration: SchemaClassDeclaration,
  file: string,
  owner: string,
  referencedNames: HashSet.HashSet<string>
): O.Option<SchemaFirstInventoryEntry> =>
  (declaration.kind === "Class" || declaration.kind === "TaggedClass") &&
  !declaration.hasInstanceMembers &&
  !declaration.hasDeclarationHooks &&
  !HashSet.has(referencedNames, declaration.symbol)
    ? O.some(
        SchemaFirstInventoryEntry.make({
          file,
          symbol: declaration.symbol,
          kind: "plain-data-schema-class",
          status: "candidate",
          reason: `Plain-data S.${declaration.kind} should be a branded S.Opaque over S.${declaration.kind === "TaggedClass" ? "TaggedStruct" : "Struct"} (D1).`,
          owner,
        })
      )
    : O.none();

// Tooling identity rule: an `S.Class<...>(...)(...)` declaration with a `$I` template identity must pass
// `$I.annote(...)` or `$I.annoteSchema(...)` in its heritage, and an `S.Opaque<...>()(...)` over an inline schema must pipe
// `$I.annoteSchema(...)` (or `$I.annote(...)`). Type arguments are parsed, so brands such as
// `{ readonly brand: unique symbol }` and nested generics never hide a class. An S.Opaque over a named schema is
// skipped: its annotation lives on that schema.
const missingIdentityAnnotationOffsets = (fileName: string, content: string): ReadonlyArray<number> => {
  const sourceFile = ts.createSourceFile(
    fileName,
    content,
    ts.ScriptTarget.Latest,
    true,
    Str.endsWith(".tsx")(fileName) ? ts.ScriptKind.TSX : ts.ScriptKind.TS
  );
  return pipe(
    scanSourceFile(sourceFile).declarations,
    A.filter(
      (declaration) =>
        !declaration.hasIdentityAnnotation &&
        ((declaration.kind === "Class" && declaration.hasIdentityTemplate) ||
          (declaration.kind === "Opaque" && declaration.hasInlineSource))
    ),
    A.map((declaration) => declaration.offset)
  );
};

/**
 * Schema-class shape detector surface used by the schema-first scan and the
 * tooling identity lint.
 *
 * **Details**
 *
 * `unbrandedEntry` turns a declaration without a nominal brand (missing or
 * structural `{}`, D4) into an `unbranded-schema-class` candidate.
 * `plainDataEntry` turns an `S.Class` / `S.TaggedClass` with no instance
 * members, no class-level `to*` Declaration hooks and no `.extend` /
 * subclass / `instanceof` / `new` / `S.instanceOf` reference anywhere in the
 * project into a `plain-data-schema-class` candidate (D1, D3); the codemod's
 * keep-class reasons the scan cannot see are inventory exceptions.
 * `missingIdentityAnnotationOffsets` finds tooling schema classes without
 * `$I.annote(...)` / `$I.annoteSchema(...)` metadata, parsing type arguments
 * so brands and nested generics never hide a class.
 *
 * **Example** (List detector names)
 *
 * ```ts
 * import { SchemaFirstSchemaClass } from "@beep/repo-cli/test/Lint"
 *
 * console.log(typeof SchemaFirstSchemaClass.scanSourceFile) // "function"
 * ```
 *
 * @category utilities
 * @since 0.0.0
 */
export const SchemaFirstSchemaClass = {
  SchemaClassBrand,
  SchemaClassDeclaration,
  SchemaClassKind,
  SchemaClassSourceScan,
  isGeneratedSourceText,
  missingIdentityAnnotationOffsets,
  plainDataEntry,
  scanSourceFile,
  unbrandedEntry,
} as const;
