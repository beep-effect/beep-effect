const runLintCommand = Command.runWith(lintCommand, { version: "0.0.0" });
const exampleShard = "standards/schema-catalog/@beep/example.generated.jsonc";
const testLayer = Layer.mergeAll(
  NodeServices.layer,
  NodeCrypto.layer,
  TestConsole.layer,
  FsUtilsLive.pipe(Layer.provide(Layer.mergeAll(NodeServices.layer, NodeCrypto.layer))),
  TSMorphServiceLive.pipe(Layer.provide(Layer.mergeAll(NodeServices.layer, NodeCrypto.layer)))
);

const writeSchemaCatalogFixture = Effect.fn("SchemaCatalogTest.writeFixture")(function* () {
  // Root marker so findRepoRoot resolves the temp fixture as the repo root.
  yield* writeProjectFile("bun.lock", "");
  yield* writeProjectFile(
    "package.json",
    A.join(
      [
        "{",
        '  "name": "@beep/test-root",',
        '  "private": true,',
        '  "type": "module",',
        '  "workspaces": ["packages/*"]',
        "}",
        "",
      ],
      "\n"
    )
  );
  yield* writeProjectFile(
    "tsconfig.json",
    A.join(
      [
        "{",
        '  "compilerOptions": {',
        '    "target": "ES2022",',
        '    "module": "ESNext",',
        '    "moduleResolution": "Bundler"',
        "  }",
        "}",
        "",
      ],
      "\n"
    )
  );
  yield* writeProjectFile(
    "packages/example/package.json",
    A.join(["{", '  "name": "@beep/example",', '  "version": "0.0.0",', '  "type": "module"', "}", ""], "\n")
  );
  yield* writeProjectFile(
    "packages/example/src/Example.ts",
    A.join(
      [
        'import { $RepoCliId } from "@beep/identity/packages";',
        'import { LiteralKit } from "@beep/schema";',
        'import * as S from "effect/Schema";',
        "",
        'const $I = $RepoCliId.create("schema-catalog-fixture");',
        "",
        "export class FixtureModel extends S.Class<FixtureModel>($I`FixtureModel`)(",
        "  { id: S.String },",
        '  $I.annote("FixtureModel", { description: "Fixture model schema." })',
        ") {}",
        "",
        'export const FixtureStatus = LiteralKit(["open", "closed"]).pipe(',
        '  $I.annoteSchema("FixtureStatus", { description: "Fixture status values." })',
        ");",
        "",
        "export const FixtureSlug = S.String.check(",
        '  S.isPattern(/^[a-z]+$/, $I.annote("FixtureSlugPattern", { description: "Lowercase letters only." }))',
        ').pipe(S.brand("FixtureSlug"), $I.annoteSchema("FixtureSlug", { description: "Fixture slug." }));',
        "",
        "export class FixtureNode extends S.Class<FixtureNode>($I`FixtureNode`)(",
        '  { kind: LiteralKit(["leaf"]).pipe($I.annoteSchema("FixtureNodeKind", { description: "Nested field." })) },',
        '  $I.annote("FixtureNode", { description: "Fixture node schema." })',
        ") {}",
        "",
        "class PrivateModel extends S.Class<PrivateModel>($I`PrivateModel`)(",
        "  { id: S.String },",
        '  $I.annote("PrivateModel", { description: "Module-local helper schema." })',
        ") {}",
        "",
        'const PrivateStatus = LiteralKit(["a", "b"]);',
        "",
        "export const usePrivates = (): ReadonlyArray<unknown> => [PrivateModel, PrivateStatus];",
        "",
      ],
      "\n"
    )
  );
});

layer(testLayer, { timeout: "30 seconds" })("schema catalog command", (it) => {
  describe("generation", () => {
    it.effect(
      "writes deterministic catalog bytes on repeated runs",
      Effect.fn("SchemaCatalogTest.deterministicWrites")(function* () {
        yield* withTempWorkingDirectory(
          Effect.gen(function* () {
            yield* writeSchemaCatalogFixture();

            yield* runLintCommand(["schema-catalog", "--write"]);
            const first = yield* readProjectFile(exampleShard);
            yield* runLintCommand(["schema-catalog", "--write"]);
            const second = yield* readProjectFile(exampleShard);

            expect(second).toBe(first);
            expect(first).toContain("// Generated by bun run beep lint schema-catalog --write.");
            expect(first).toContain('"schemaVersion": "schema-catalog-shard/v1"');
            expect(first).toContain('"generatedBy": "bun run beep lint schema-catalog --write"');
            expect(first).toContain('"owner": "@beep/example"');
            expect(first).toContain(
              '    {"file":"packages/example/src/Example.ts","symbol":"FixtureModel","kind":"schema-class","owner":"@beep/example","identity":"FixtureModel","description":"Fixture model schema."}'
            );
          })
        );
      })
    );

    it.effect(
      "catalogs a fixture S.Class with kind and owner",
      Effect.fn("SchemaCatalogTest.fixtureEntry")(function* () {
        yield* withTempWorkingDirectory(
          Effect.gen(function* () {
            yield* writeSchemaCatalogFixture();
            const document = yield* generateSchemaCatalogDocument();
            const entry = A.findFirst(
              document.entries,
              (candidate) => candidate.file === "packages/example/src/Example.ts" && candidate.symbol === "FixtureModel"
            );

            entry.pipe(O.isSome, assertTrue);
            if (O.isSome(entry)) {
              expect(entry.value.kind).toBe("schema-class");
              expect(entry.value.owner).toBe("@beep/example");
              expect(entry.value.identity).toBe("FixtureModel");
              expect(entry.value.description).toBe("Fixture model schema.");
            }

            // A declaration is named by its own annotation, never by a nested check argument or field schema.
            const identityOf = (symbol: string) =>
              A.findFirst(document.entries, (candidate) => candidate.symbol === symbol).pipe(
                O.map(({ identity, description }) => ({ identity, description }))
              );
            assertSome(identityOf("FixtureSlug"), { identity: "FixtureSlug", description: "Fixture slug." });
            assertSome(identityOf("FixtureNode"), { identity: "FixtureNode", description: "Fixture node schema." });

            // Non-exported declarations are private helpers, not catalog surface.
            const symbols = A.map(document.entries, (candidate) => candidate.symbol);
            expect(A.contains(symbols, "PrivateModel")).toBe(false);
            expect(A.contains(symbols, "PrivateStatus")).toBe(false);
          })
        );
      })
    );

    it.effect(
      "fails check mode when the tracked catalog is stale",
      Effect.fn("SchemaCatalogTest.staleCheck")(function* () {
        yield* withTempWorkingDirectory(
          Effect.gen(function* () {
            yield* writeSchemaCatalogFixture();
            yield* writeProjectFile(exampleShard, "// stale\n{}\n");

            const exit = yield* Effect.exit(runLintCommand(["schema-catalog"]));
            const errorLines = yield* TestConsole.errorLines;

            expectReportedExit(exit);
            expect(errorLines).toContain(`[schema-catalog] stale ${exampleShard}`);
          })
        );
      })
    );

    it.effect(
      "reports the retired single-file catalog as orphaned and write mode removes it",
      Effect.fn("SchemaCatalogTest.retiredMonolith")(function* () {
        yield* withTempWorkingDirectory(
          Effect.gen(function* () {
            yield* writeSchemaCatalogFixture();
            yield* runLintCommand(["schema-catalog", "--write"]);
            yield* writeProjectFile("standards/schema-catalog.generated.jsonc", "// retired\n{}\n");

            const exit = yield* Effect.exit(runLintCommand(["schema-catalog"]));
            expectReportedExit(exit);
            expect(yield* TestConsole.errorLines).toContain(
              "[schema-catalog] orphaned standards/schema-catalog.generated.jsonc"
            );

            yield* runLintCommand(["schema-catalog", "--write"]);
            yield* runLintCommand(["schema-catalog"]);
            expect(yield* TestConsole.logLines).toContain(
              "[schema-catalog] removed standards/schema-catalog.generated.jsonc"
            );
          })
        );
      })
    );
  });

  describe("sharding", () => {
    const entry = (owner: string, file: string, symbol: string) =>
      SchemaCatalogEntry.make({ file, symbol, kind: "schema-class", owner });
    const shardsOf = (entries: ReadonlyArray<SchemaCatalogEntry>) =>
      generateSchemaCatalogShards(
        SchemaCatalogDocument.make({
          schemaVersion: "schema-catalog/v1",
          generatedBy: "bun run beep lint schema-catalog --write",
          entries,
        })
      );
    const changed = (
      before: ReadonlyArray<{ readonly path: string; readonly content: string }>,
      after: ReadonlyArray<{ readonly path: string; readonly content: string }>
    ) =>
      A.map(
        A.filter(after, (shard) => !A.some(before, (old) => old.path === shard.path && old.content === shard.content)),
        (shard) => shard.path
      );

    it.effect(
      "keeps schema additions in different packages in disjoint shard files",
      Effect.fn("SchemaCatalogTest.disjointShards")(function* () {
        const base = [
          entry("@beep/a", "packages/a/src/A.ts", "Alpha"),
          entry("@beep/b", "packages/b/src/B.ts", "Beta"),
        ];
        const main = yield* shardsOf(base);
        const left = yield* shardsOf([...base, entry("@beep/a", "packages/a/src/A.ts", "Alpha2")]);
        const right = yield* shardsOf([...base, entry("@beep/b", "packages/b/src/B.ts", "Beta2")]);

        expect(A.map(main, (shard) => shard.path)).toEqual([
          "standards/schema-catalog/@beep/a.generated.jsonc",
          "standards/schema-catalog/@beep/b.generated.jsonc",
        ]);
        expect(changed(main, left)).toEqual(["standards/schema-catalog/@beep/a.generated.jsonc"]);
        expect(changed(main, right)).toEqual(["standards/schema-catalog/@beep/b.generated.jsonc"]);
      })
    );

    it.effect(
      "refuses an owner that is not a scoped package name",
      Effect.fn("SchemaCatalogTest.invalidOwner")(function* () {
        const exit = yield* Effect.exit(shardsOf([entry("../escape", "packages/x/src/X.ts", "X")]));
        exit.pipe(Exit.isFailure, assertTrue);
      })
    );
  });
});
