describe("decideFinalCheckRefresh", () => {
  const facts = (ownChanges: ReadonlyArray<string>, drift: ReadonlyArray<FinalCheckStatusDrift> = []) =>
    FinalCheckRefreshFacts.make({
      receipt: receiptFor(Str.repeat(40)("r")),
      finalHead: Str.repeat(40)("f"),
      ownChanges,
      effectVitestStatusDrift: drift,
      effectVitestUnreadable: O.none(),
    });

  it("refuses code before it looks at effect-vitest drift", () => {
    const verdict = decideFinalCheckRefresh(
      facts(["src/a.ts", EFFECT_VITEST], [FinalCheckStatusDrift.make({ status: "open", atReceipt: 0, atFinal: 1 })])
    );
    assertTrue(verdict._tag === "refused" && verdict.reason === "own-change-outside-allowlist");
  });

  it("fails closed when the effect-vitest inventory cannot be decoded at a revision", () => {
    const verdict = decideFinalCheckRefresh(
      FinalCheckRefreshFacts.make({ ...facts([EFFECT_VITEST]), effectVitestUnreadable: O.some("abc") })
    );
    assertTrue(verdict._tag === "refused" && verdict.reason === "effect-vitest-status-drift");
  });

  it("renders a drift the lane lost at the receipt with its sign", () => {
    const verdict = decideFinalCheckRefresh(
      facts([EFFECT_VITEST], [FinalCheckStatusDrift.make({ status: "exception", atReceipt: -1, atFinal: 0 })])
    );
    assertTrue(verdict._tag === "refused");
    expect(verdict.detail).toContain("exception -1 at the receipt, +0 at the final head");
  });
});

