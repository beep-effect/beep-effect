/**
 * Encodes a {@link BrandIdentity} as a Tailwind v4 theme stylesheet.
 *
 * @packageDocumentation
 * @since 0.0.0
 */
import { A, Str } from "@beep/utils";
import { pipe } from "effect";
import { ScaleStep, SurfaceStep } from "./Brand.schema.ts";
import type { BrandIdentity, ColorScheme, FontStack, Glow, GlowLayer, GlowStop, Typography } from "./Brand.schema.ts";

/**
 * Banner line at the top of every generated stylesheet.
 *
 * **Example** (Detect a generated stylesheet)
 *
 * ```ts
 * import { GENERATED_CSS_BANNER } from "@beep/brand"
 *
 * console.log(GENERATED_CSS_BANNER.startsWith("/*"))
 * ```
 *
 * @category rendering
 * @since 0.0.0
 */
export const GENERATED_CSS_BANNER =
  "/* Generated by @beep/brand from Brand.tokens.ts. Do not edit by hand; run `bun run render` in packages/foundation/ui-system/brand. */";

const declaration = (name: string, value: string): string => `  --${name}: ${value};`;

const block = (selector: string, lines: ReadonlyArray<string>): string =>
  pipe([`${selector} {`, ...lines, "}"], A.join("\n"));

const quoteFamily = (family: string): string => (Str.includes(" ")(family) ? `"${family}"` : family);

const fontStack = (stack: FontStack): string =>
  pipe([stack.family, ...stack.fallbacks], A.map(quoteFamily), A.join(", "));

const scaleLines = (scheme: ColorScheme): ReadonlyArray<string> =>
  A.map(ScaleStep.Options, (step) => declaration(`color-brand-${step}`, scheme.brand[step]));

const surfaceLines = (scheme: ColorScheme): ReadonlyArray<string> =>
  A.map(SurfaceStep.Options, (step) => declaration(`color-surface-${step}`, scheme.surface[step]));

const roleLines = (scheme: ColorScheme): ReadonlyArray<string> => [
  declaration("color-fg", scheme.foreground.base),
  declaration("color-fg-muted", scheme.foreground.muted),
  declaration("color-fg-subtle", scheme.foreground.subtle),
  declaration("color-border", scheme.border.base),
  declaration("color-border-hover", scheme.border.hover),
  declaration("color-success", scheme.semantic.success),
  declaration("color-warning", scheme.semantic.warning),
  declaration("color-error", scheme.semantic.error),
];

const glowValue = (stop: GlowStop): string =>
  `color-mix(in srgb, var(--color-brand-${stop.step}) ${Math.round(stop.alpha * 100)}%, transparent)`;

const glowLayerLines = (name: string, layer: GlowLayer): ReadonlyArray<string> => [
  declaration(`beep-glow-${name}-start`, glowValue(layer.start)),
  declaration(`beep-glow-${name}-mid`, glowValue(layer.mid)),
];

const glowLines = (glow: Glow): ReadonlyArray<string> =>
  A.flatten([
    glowLayerLines("primary", glow.primary),
    glowLayerLines("secondary", glow.secondary),
    glowLayerLines("tertiary", glow.tertiary),
  ]);

const fontLines = (typography: Typography): ReadonlyArray<string> => [
  declaration("font-brand-sans", fontStack(typography.sans)),
  declaration("font-brand-mono", fontStack(typography.mono)),
  declaration("font-sans", "var(--font-brand-sans)"),
  declaration("font-mono", "var(--font-brand-mono)"),
];

const schemeLines = (scheme: ColorScheme): ReadonlyArray<string> =>
  A.flatten([scaleLines(scheme), surfaceLines(scheme), roleLines(scheme)]);

/**
 * Render the brand theme stylesheet.
 *
 * **Details**
 *
 * The light scheme is declared inside `@theme` so Tailwind v4 mints `bg-brand-500`,
 * `text-fg-muted`, `border-border-hover`, and `font-brand-mono` utilities. The dark
 * scheme redeclares the same custom properties under `.dark`, matching the `.dark`
 * custom variant that `@beep/ui/styles/globals.css` uses, so utilities follow the
 * appearance without inline theme values. Glow layers are `color-mix()` references
 * to the brand scale rather than baked RGBA, so they track scheme overrides.
 *
 * **Example** (Render the beep theme)
 *
 * ```ts
 * import { beep, renderThemeCss } from "@beep/brand"
 *
 * const css = renderThemeCss(beep)
 * console.log(css.includes("--color-brand-500"))
 * ```
 *
 * @param identity - Brand identity to encode.
 * @returns The stylesheet text, ending with a newline.
 * @category rendering
 * @since 0.0.0
 */
export const renderThemeCss = (identity: BrandIdentity): string =>
  pipe(
    [
      GENERATED_CSS_BANNER,
      block("@theme", A.flatten([schemeLines(identity.light), fontLines(identity.typography)])),
      block(":root", glowLines(identity.light.glow)),
      block(".dark", A.flatten([schemeLines(identity.dark), glowLines(identity.dark.glow)])),
    ],
    A.join("\n\n"),
    Str.concat("\n")
  );
