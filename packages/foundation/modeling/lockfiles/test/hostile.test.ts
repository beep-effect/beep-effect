import { Lockfile, LockfileParseError } from "@beep/lockfiles/Lockfile";
import { isUnsupportedLockfileVersion } from "@beep/lockfiles/UnsupportedLockfileVersion";
import { assert, describe, it } from "@effect/vitest";
import { assertNone, assertSome, assertTrue } from "@effect/vitest/utils";
import * as A from "effect/Array";
import * as Effect from "effect/Effect";
import * as O from "effect/Option";
import * as P from "effect/Predicate";
import * as R from "effect/Record";
import * as S from "effect/Schema";
import * as Str from "effect/String";
import type { LockfileFormat } from "@beep/lockfiles/LockfileFormat";

const JsonString = S.fromJsonString(S.Unknown);

const parseError = Effect.fn("parseError")(function* (content: string, format: LockfileFormat) {
  const error = yield* Effect.flip(Lockfile.parse(content, { format }));
  assert.instanceOf(error, LockfileParseError);
  assert.strictEqual(error.format, format);
  return error;
});

const assertPrototypeUnpolluted = (): void => {
  const empty: Record<string, unknown> = {};
  assert.strictEqual(empty.polluted, undefined);
  assert.isFalse(P.hasProperty(Object.prototype, "polluted"));
};

describe("hostile input exits through the typed LockfileParseError, never a defect, prototype write or overflow", () => {
  describe("malformed text fails at stage 'syntax'", () => {
    it.effect("pnpm: broken YAML", () =>
      Effect.gen(function* () {
        const error = yield* parseError("importers:\n  - [unclosed\n\tflow", "pnpm");
        assert.strictEqual(error.stage, "syntax");
      })
    );

    it.effect("yarn: broken YAML", () =>
      Effect.gen(function* () {
        const error = yield* parseError('"a@npm:^1":\n  version: "1\n', "yarn");
        assert.strictEqual(error.stage, "syntax");
      })
    );

    it.effect("npm: broken JSON", () =>
      Effect.gen(function* () {
        const error = yield* parseError("{ definitely not json", "npm");
        assert.strictEqual(error.stage, "syntax");
      })
    );

    it.effect("bun: broken JSONC", () =>
      Effect.gen(function* () {
        const error = yield* parseError('{ "lockfileVersion": 1, /* unclosed comment', "bun");
        assert.strictEqual(error.stage, "syntax");
      })
    );
  });

  describe("well-formed text with the wrong shape fails at stage 'validation'", () => {
    it.effect("pnpm: missing importers", () =>
      Effect.gen(function* () {
        const error = yield* parseError("lockfileVersion: '9.0'\n", "pnpm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("pnpm: importers of the wrong type", () =>
      Effect.gen(function* () {
        const error = yield* parseError("lockfileVersion: '9.0'\nimporters: 42\n", "pnpm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("npm: missing lockfileVersion", () =>
      Effect.gen(function* () {
        const error = yield* parseError("{}", "npm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("npm: a top-level array", () =>
      Effect.gen(function* () {
        const error = yield* parseError("[1, 2, 3]", "npm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("yarn: a top-level scalar", () =>
      Effect.gen(function* () {
        const error = yield* parseError("42\n", "yarn");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("yarn: an entry of the wrong type", () =>
      Effect.gen(function* () {
        const error = yield* parseError('"a@npm:^1.0.0": 42\n', "yarn");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("bun: missing lockfileVersion", () =>
      Effect.gen(function* () {
        const error = yield* parseError("{}", "bun");
        assert.strictEqual(error.stage, "validation");
      })
    );
  });

  describe("yarn classic (v1) content is rejected, never mis-normalized", () => {
    const classic = A.join(
      [
        "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
        "# yarn lockfile v1",
        "",
        "",
        "lodash@^4.17.21:",
        '  version "4.17.21"',
        '  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#679591c564c3bffaae8454cf0b3df370c3d6911c"',
        "  integrity sha512-v2kDEe57lecTulaDIuNTPy3Ry4gLGJ6Z1O3vE1krgXZNrsQ+LFTGHVxVjcXPs17LhbZVGedAJv8XZ1tvj5FvSg==",
        "",
      ],
      "\n"
    );

    it.effect("fails typed with format 'yarn'", () =>
      Effect.gen(function* () {
        const error = yield* parseError(classic, "yarn");
        assert.strictEqual(
          error.stage,
          "validation",
          "classic content happens to YAML-parse as plain scalars, so only Berry entry validation rejects it"
        );
      })
    );
  });

  describe("prototype-pollution discipline", () => {
    it.effect("a __proto__ pnpm importer neither pollutes nor crashes", () =>
      Effect.gen(function* () {
        const content = A.join(
          [
            "lockfileVersion: '9.0'",
            "importers:",
            "  __proto__:",
            "    dependencies:",
            "      polluted:",
            "        specifier: '1.0.0'",
            "        version: 1.0.0",
            "  constructor:",
            "    devDependencies:",
            "      polluted:",
            "        specifier: '1.0.0'",
            "        version: 1.0.0",
          ],
          "\n"
        );
        const lockfile = yield* Lockfile.parse(content, { format: "pnpm" });
        assertPrototypeUnpolluted();
        assert.deepStrictEqual(
          A.map(lockfile.workspacePackages, (p) => p.name).sort(),
          ["__proto__", "constructor"],
          "hostile importer names are data in Map-backed intermediates and schema-decoded records"
        );
      })
    );

    it.effect("__proto__ npm package keys and dependency maps neither pollute nor crash", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 3,
          packages: {
            "": { name: "root" },
            "node_modules/__proto__": {
              version: "1.0.0",
              dependencies: R.fromEntries([
                ["__proto__", "1.0.0"],
                ["constructor", "2.0.0"],
              ]),
            },
            "node_modules/constructor": { version: "1.0.0" },
          },
        });
        assert.include(
          content,
          '"__proto__":"1.0.0"',
          "an object literal swallows a __proto__ key, so R.fromEntries builds the own property"
        );
        const lockfile = yield* Lockfile.parse(content, { format: "npm" });
        assertPrototypeUnpolluted();
        assert.strictEqual(lockfile.packagesNamed("__proto__").length, 1);
        assert.strictEqual(lockfile.packagesNamed("constructor").length, 1);
        const evil = O.getOrThrow(A.head(lockfile.packagesNamed("__proto__")));
        const ownProtoDependency = A.findFirst(R.toEntries(evil.dependencies), ([k]) => k === "__proto__");
        assertSome(ownProtoDependency, ["__proto__", "1.0.0"]);
        assert.strictEqual(evil.instanceId, "node_modules/__proto__");
        const ownProtoResolvedEdge = A.findFirst(R.toEntries(evil.resolved), ([k]) => k === "__proto__");
        assertSome(ownProtoResolvedEdge, ["__proto__", "node_modules/__proto__"]);
        assertPrototypeUnpolluted();
      })
    );

    it.effect("a __proto__ importer path and dependency name populate importers without polluting", () =>
      Effect.gen(function* () {
        const content = A.join(
          [
            "lockfileVersion: '9.0'",
            "importers:",
            "  __proto__:",
            "    dependencies:",
            "      __proto__:",
            "        specifier: '1.0.0'",
            "        version: 1.0.0",
            "  .: {}",
          ],
          "\n"
        );
        const lockfile = yield* Lockfile.parse(content, { format: "pnpm" });
        assertPrototypeUnpolluted();

        const evil = O.getOrThrow(lockfile.importer("__proto__"));
        assert.strictEqual(evil.path, "__proto__", "the Map-backed importer index holds a hostile path as data");
        const dep = O.getOrThrow(evil.dependency("__proto__"));
        assert.strictEqual(dep.specifier.raw, "1.0.0");
        assert.strictEqual(dep.specifier._tag, "range");

        assertSome(
          O.map(lockfile.importer("."), () => true),
          true
        );
      })
    );

    it.effect("__proto__-keyed peer maps neither pollute nor drop, in every format", () =>
      Effect.gen(function* () {
        const hostilePeers = R.fromEntries([
          ["__proto__", "^1.0.0"],
          ["constructor", "^2.0.0"],
        ]);
        const hostileMeta = R.fromEntries([["__proto__", { optional: true }]]);

        const npmContent = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 3,
          packages: {
            "": { name: "root" },
            "node_modules/evil": {
              version: "1.0.0",
              peerDependencies: hostilePeers,
              peerDependenciesMeta: hostileMeta,
            },
          },
        });
        assert.include(
          npmContent,
          '"__proto__":"^1.0.0"',
          "a hostile peer name is built with R.fromEntries, since an object literal swallows __proto__"
        );

        const bunContent = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 1,
          workspaces: { "": { name: "root" } },
          packages: {
            evil: ["evil@1.0.0", "", { peerDependencies: hostilePeers, optionalPeers: ["__proto__"] }],
          },
        });

        for (const [format, content] of [
          ["npm", npmContent],
          ["bun", bunContent],
        ] as const) {
          const lockfile = yield* Lockfile.parse(content, { format });
          assertPrototypeUnpolluted();
          const evil = O.getOrThrow(A.head(lockfile.packagesNamed("evil")));
          assert.deepStrictEqual(
            A.findFirst(R.toEntries(evil.peerDependencies), ([k]) => k === "__proto__"),
            O.some<[string, string]>(["__proto__", "^1.0.0"]),
            `${format}: hostile peer range is an own enumerable property, not dropped`
          );
          assert.deepStrictEqual(
            A.findFirst(R.toEntries(evil.peerDependenciesMeta), ([k]) => k === "__proto__"),
            O.some<[string, { readonly optional: boolean }]>(["__proto__", { optional: true }]),
            `${format}: hostile peer meta is an own enumerable property, not dropped`
          );
        }
      })
    );

    it.effect("a __proto__ bun workspace neither pollutes nor crashes", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 1,
          workspaces: {
            "": { name: "root" },
            "packages/evil": { name: "__proto__", version: "1.0.0" },
          },
        });
        const lockfile = yield* Lockfile.parse(content, { format: "bun" });
        assertPrototypeUnpolluted();
        assert.strictEqual(lockfile.workspacePackages[0]?.name, "__proto__");
      })
    );
  });

  describe("hostile name@version keys are skipped, never thrown on", () => {
    it.effect("pnpm: '@', '@scope/', bare and empty keys", () =>
      Effect.gen(function* () {
        const content = A.join(
          [
            "lockfileVersion: '9.0'",
            "importers:",
            "  .: {}",
            "packages:",
            "  '@': {}",
            "  '@scope/': {}",
            "  bare-no-at: {}",
            "  'ok@1.0.0': {}",
          ],
          "\n"
        );
        const lockfile = yield* Lockfile.parse(content, { format: "pnpm" });
        assert.deepStrictEqual(
          A.map(lockfile.packages, (p) => [p.name, p.version]),
          [["ok", "1.0.0"]]
        );
      })
    );

    it.effect("bun: malformed and non-string package tuples", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 1,
          packages: {
            "empty-tuple": [],
            "non-string-id": [42],
            "lone-at": ["@"],
            "slash-without-version": ["@scope/"],
            e: ["no-at-sign"],
            f: ["ok@1.0.0", "", {}, "sha512-abc"],
          },
        });
        const lockfile = yield* Lockfile.parse(content, { format: "bun" });
        assert.deepStrictEqual(
          A.map(lockfile.packages, (p) => [p.name, p.version, p.integrity]),
          [["ok", "1.0.0", "sha512-abc"]]
        );
      })
    );

    it.effect("yarn: descriptors without an extractable name", () =>
      Effect.gen(function* () {
        const emptyNameDescriptor = '"@npm:^1.0.0": {}';
        const content = A.join(
          [
            "__metadata:",
            "  version: 8",
            emptyNameDescriptor,
            '"no-descriptor-at-all": {}',
            '"ok@npm:^1.0.0":',
            '  version: "1.2.3"',
          ],
          "\n"
        );
        const lockfile = yield* Lockfile.parse(content, { format: "yarn" });
        assert.deepStrictEqual(
          A.map(lockfile.packages, (p) => [p.name, p.version]),
          [["ok", "1.2.3"]]
        );
      })
    );
  });

  describe("a present but unparseable integrity fails typed at stage 'validation'; yarn, SRI and corepack forms pass", () => {
    const CORRUPT = "not-a-valid-integrity";

    it.effect("npm: a corrupt package integrity", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 3,
          packages: {
            "": { name: "root" },
            "node_modules/foo": { version: "1.0.0", integrity: CORRUPT },
          },
        });
        const error = yield* parseError(content, "npm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("pnpm: a corrupt package resolution integrity", () =>
      Effect.gen(function* () {
        const content = A.join(
          [
            "lockfileVersion: '9.0'",
            "importers:",
            "  .: {}",
            "packages:",
            "  'foo@1.0.0':",
            "    resolution:",
            `      integrity: ${CORRUPT}`,
          ],
          "\n"
        );
        const error = yield* parseError(content, "pnpm");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("yarn: a corrupt entry checksum", () =>
      Effect.gen(function* () {
        const content = A.join(
          ["__metadata:", "  version: 8", '"ok@npm:^1.0.0":', '  version: "1.2.3"', `  checksum: ${CORRUPT}`],
          "\n"
        );
        const error = yield* parseError(content, "yarn");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("bun: a corrupt package-tuple integrity", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 1,
          packages: { foo: ["foo@1.0.0", "", {}, CORRUPT] },
        });
        const error = yield* parseError(content, "bun");
        assert.strictEqual(error.stage, "validation");
      })
    );

    it.effect("an absent integrity is omitted and the parse succeeds", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 3,
          packages: {
            "": { name: "root" },
            "node_modules/foo": { version: "1.0.0" },
          },
        });
        const lockfile = yield* Lockfile.parse(content, { format: "npm" });
        const foo = lockfile.packagesNamed("foo")[0];
        assert.strictEqual(foo?.integrity, undefined);
      })
    );
  });

  describe("empty importer paths are skipped before a NonEmptyString LockfileImporter.path would die as a defect", () => {
    it.effect("npm: a link entry with an empty resolved path is skipped, parse succeeds", () =>
      Effect.gen(function* () {
        const content = yield* S.encodeEffect(JsonString)({
          lockfileVersion: 3,
          packages: {
            "": { name: "root" },
            "node_modules/pkg": { link: true, resolved: "" },
          },
        });
        const lockfile = yield* Lockfile.parse(content, { format: "npm" });
        assertNone(lockfile.importer(""));
        assertSome(
          O.map(lockfile.importer("."), () => true),
          true
        );
      })
    );

    it.effect("pnpm: an empty importer key is skipped, parse succeeds", () =>
      Effect.gen(function* () {
        const content = A.join(["lockfileVersion: '9.0'", "importers:", "  '': {}", "  .: {}"], "\n");
        const lockfile = yield* Lockfile.parse(content, { format: "pnpm" });
        assertNone(lockfile.importer(""));
        assertSome(
          O.map(lockfile.importer("."), () => true),
          true
        );
      })
    );
  });

  describe("deep-nesting bombs surface the delegated engines' typed failures", () => {
    it.effect("npm: a deeply nested JSON document fails typed, never a defect", () =>
      Effect.gen(function* () {
        const depth = 200_000;
        const content = Str.repeat(depth)("[") + Str.repeat(depth)("]");
        const error = yield* parseError(content, "npm");
        assert.isTrue(
          error.stage === "syntax" || error.stage === "validation",
          "a V8 RangeError on depth or the top-level array shape check, either way typed"
        );
      })
    );

    it.effect("pnpm: a YAML flow-nesting bomb fails typed", () =>
      Effect.gen(function* () {
        const error = yield* parseError(`importers: ${Str.repeat(10_000)("[")}`, "pnpm");
        assert.strictEqual(error.stage, "syntax");
      })
    );

    it.effect("yarn: a YAML flow-nesting bomb fails typed", () =>
      Effect.gen(function* () {
        const error = yield* parseError(`entry: ${Str.repeat(10_000)("{a: ")}`, "yarn");
        assert.strictEqual(error.stage, "syntax");
      })
    );

    it.effect("bun: a JSONC nesting bomb fails typed", () =>
      Effect.gen(function* () {
        const content = `{"lockfileVersion": 1, "packages": ${Str.repeat(10_000)("[")}`;
        const error = yield* parseError(content, "bun");
        assert.strictEqual(error.stage, "syntax");
      })
    );
  });

  describe("non-finite recorded versions fail boundary validation", () => {
    it.effect("npm: overflow is rejected before the version gate", () =>
      Effect.gen(function* () {
        for (const recorded of ["1e999", "-1e999"]) {
          const error = yield* parseError(`{"lockfileVersion":${recorded},"packages":{}}`, "npm");
          assert.strictEqual(error.stage, "validation");
          assert.isFalse(isUnsupportedLockfileVersion(error.cause));
          assertTrue(S.isSchemaError(error.cause));
          assert.include(error.cause.message, "lockfileVersion");
          assert.include(error.cause.message, "finite");
        }
      })
    );

    it.effect("pnpm: infinities and NaN are rejected before the version gate", () =>
      Effect.gen(function* () {
        for (const recorded of [".inf", "-.inf", ".nan"]) {
          const error = yield* parseError(`lockfileVersion: ${recorded}\nimporters: {}\n`, "pnpm");
          assert.strictEqual(error.stage, "validation");
          assert.isFalse(isUnsupportedLockfileVersion(error.cause));
          assertTrue(S.isSchemaError(error.cause));
          assert.include(error.cause.message, "lockfileVersion");
          assert.include(error.cause.message, "finite");
        }
      })
    );

    it.effect("bun: overflow fails finite version validation", () =>
      Effect.gen(function* () {
        for (const recorded of ["1e999", "-1e999"]) {
          const error = yield* parseError(`{"lockfileVersion":${recorded},"packages":{}}`, "bun");
          assert.strictEqual(error.stage, "validation");
          assertTrue(S.isSchemaError(error.cause));
          assert.include(error.cause.message, "lockfileVersion");
          assert.include(error.cause.message, "finite");
        }
      })
    );

    it.effect("yarn: infinities and NaN fail finite metadata validation", () =>
      Effect.gen(function* () {
        for (const recorded of [".inf", "-.inf", ".nan"]) {
          const error = yield* parseError(`__metadata:\n  version: ${recorded}\n`, "yarn");
          assert.strictEqual(error.stage, "validation");
          assertTrue(S.isSchemaError(error.cause));
          assert.include(error.cause.message, "version");
          assert.include(error.cause.message, "finite");
        }
      })
    );
  });

  it.effect("unsupported version messages preserve JSON scalar quoting and escaping exactly", () =>
    Effect.gen(function* () {
      for (const [raw, rendered] of [
        [2, "2"],
        ["2", '"2"'],
        ['next"\\\n', '"next\\"\\\\\\n"'],
      ] as const) {
        const value = yield* S.encodeEffect(JsonString)({ lockfileVersion: raw });
        const error = yield* parseError(value, "npm");
        assert.strictEqual(error.stage, "validation");
        const cause = error.cause;
        assertTrue(isUnsupportedLockfileVersion(cause));
        assert.strictEqual(cause.lockfileVersion, raw);
        assert.strictEqual(
          cause.message,
          `npm lockfileVersion ${rendered} is not supported: @effected/lockfiles parses npm lockfileVersion 3 and newer`
        );
      }
    })
  );

  describe("error surface", () => {
    it.effect("LockfileParseError message names the format and stage", () =>
      Effect.gen(function* () {
        const error = yield* parseError("{ nope", "npm");
        assert.strictEqual(error._tag, "LockfileParseError");
        assert.include(error.message, "npm");
        assert.include(error.message, "not well-formed");
      })
    );

    it.effect("the underlying cause is preserved structurally, not stringified", () =>
      Effect.gen(function* () {
        const error = yield* parseError("{ nope", "npm");
        assertTrue(S.isSchemaError(error.cause));
        assert.strictEqual(error.stage, "syntax");
        assert.strictEqual(error.cause.message, "Expected a valid JSON string");
        assertTrue(error.cause.issue._tag === "Encoding");
        assert.strictEqual(error.cause.issue.issue._tag, "InvalidValue");
      })
    );
  });
});
