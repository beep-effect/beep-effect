#!/usr/bin/env bun
/**
 * Regenerates `src/internal/entityMap.ts` from the WHATWG HTML standard's
 * named character reference document.
 *
 * Run it with `bun run generate:entities`, which also formats the written
 * module with Biome. The fetch goes through the `effect/http` client and the
 * write through `effect/FileSystem`, both provided by the Node services layer.
 *
 * @since 0.0.0
 */
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import * as A from "effect/Array";
import * as DateTime from "effect/DateTime";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import { identity, pipe } from "effect/Function";
import * as FetchHttpClient from "effect/http/FetchHttpClient";
import * as HttpClient from "effect/http/HttpClient";
import * as HttpClientResponse from "effect/http/HttpClientResponse";
import * as Layer from "effect/Layer";
import * as Order from "effect/Order";
import * as Path from "effect/Path";
import * as R from "effect/Record";
import * as Result from "effect/Result";
import * as S from "effect/Schema";
import * as Str from "effect/String";
import * as Tuple from "effect/Tuple";

const SOURCE = "https://html.spec.whatwg.org/entities.json";

/** The document's shape: `&name;` keys, each with its replacement string. */
const EntitiesDocument = S.Record(S.String, S.Struct({ characters: S.String }));

const byName: Order.Order<readonly [string, string]> = Order.mapInput(Order.String, ([name]) => name);

/** The semicolon-terminated names, stripped of `&` and `;`, in code-unit order. */
const entriesOf = (document: typeof EntitiesDocument.Type): ReadonlyArray<readonly [string, string]> =>
  pipe(
    R.toEntries(document),
    A.filter(([name]) => Str.endsWith(";")(name)),
    A.map(([name, { characters }]) => Tuple.make(Str.slice(1, -1)(name), characters)),
    A.sort(byName)
  );

const render = (
  entries: ReadonlyArray<readonly [string, string]>,
  fetchedOn: string
): string => `// Generated by scripts/generate-entities.ts — do not edit by hand.
//
// The HTML5 named character references, from the WHATWG HTML standard's
// entity document (${SOURCE}, fetched ${fetchedOn});
// the human-readable table is at
// https://html.spec.whatwg.org/multipage/named-characters.html.
//
// Only the semicolon-terminated names are here: CommonMark's entity grammar
// requires the semicolon, so the legacy unterminated forms cannot match.
//
// Stored as JSON and parsed once at module load — a ${entries.length}-entry
// Map literal costs several times this in source size, and the parse is a
// one-off. Leaf module: imports only Effect codecs.

import * as HashMap from "effect/HashMap";
import * as Result from "effect/Result";
import * as S from "effect/Schema";

const DATA = ${Result.getOrThrowWith(S.encodeUnknownResult(S.fromJsonString(S.Unknown))(Result.getOrThrowWith(S.encodeUnknownResult(S.fromJsonString(S.Unknown))(entries), identity)), identity)};

const decodeEntities = S.Tuple([S.String, S.String]).pipe(S.Array, S.fromJsonString, S.decodeResult);

/**
 * The HTML5 named character references, keyed without \`&\` or \`;\`.
 *
 * **Example** (Look up a named character reference)
 *
 * \`\`\`ts
 * import * as HashMap from "effect/HashMap"
 * import * as O from "effect/Option"
 * import { ENTITY_MAP } from "@beep/markdown/internal/entityMap"
 *
 * console.log(O.getOrElse(HashMap.get(ENTITY_MAP, "amp"), () => "missing")) // &
 * console.log(HashMap.has(ENTITY_MAP, "&amp;")) // false
 * console.log(O.isNone(HashMap.get(ENTITY_MAP, "unknown"))) // true
 * \`\`\`
 *
 * @category constants
 * @since 0.0.0
 */
export const ENTITY_MAP: HashMap.HashMap<string, string> = decodeEntities(DATA).pipe(
  Result.getOrThrow,
  HashMap.fromIterable
);
`;

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const response = yield* HttpClient.get(SOURCE).pipe(Effect.flatMap(HttpClientResponse.filterStatusOk));
  const document = yield* HttpClientResponse.schemaBodyJson(EntitiesDocument)(response);
  const entries = entriesOf(document);
  const now1 = yield* DateTime.now;
  const fetchedOn = DateTime.formatIsoDateUtc(now1);
  const target = path.join(import.meta.dirname, "..", "src", "internal", "entityMap.ts");
  yield* fs.writeFileString(target, render(entries, fetchedOn));
  yield* Effect.log(`wrote ${entries.length} entities to ${target}`);
});

// The fetch needs an HTTP client and the write a file system; both come from
// one scoped build of the platform layers.
const main = Effect.scoped(
  Effect.gen(function* () {
    const platform = yield* Layer.build(Layer.mergeAll(NodeServices.layer, FetchHttpClient.layer));
    return yield* Effect.provide(program, platform);
  })
);

if (import.meta.main) {
  NodeRuntime.runMain(main);
}
