/**
 * Strict known-shape decoder for the ratified S6 admission-policy A-Box.
 *
 * @packageDocumentation
 * @since 0.0.0
 */

import { FiniteFromString, PosInt } from "@beep/schema";
import { Effect, pipe } from "effect";
import * as A from "effect/Array";
import * as Str from "effect/String";
import { AdmissionPolicyParams, AdmissionPriority, AdmissionTokenWeights, PolicyDecodeError } from "./Schemas.ts";

// The pattern binds the complete committed document shape while leaving every
// policy value and declared priority to be decoded from artifact bytes.
const knownAboxShape =
  /^# GENERATED by scripts\/build_abox\.py — do not hand-edit\.\n# Ratified S6 policy and deployed enumeration A-Box\.\n@prefix ciops: <https:\/\/oip\.law\/ontology\/ci-ops#> \.\n@prefix rdf: <http:\/\/www\.w3\.org\/1999\/02\/22-rdf-syntax-ns#> \.\n@prefix xsd: <http:\/\/www\.w3\.org\/2001\/XMLSchema#> \.\n\nciops:YeetWeightedAdmissionV1 rdf:type ciops:AdmissionPolicy ;\n {4}ciops:capacityMaxTokens "([0-9]+)"\^\^xsd:integer ;\n {4}ciops:slotSizeGib "([0-9]+)"\^\^xsd:decimal ;\n {4}ciops:reserveGib "([0-9]+)"\^\^xsd:decimal ;\n {4}ciops:hardFloorGib "([0-9]+)"\^\^xsd:decimal ;\n {4}ciops:heartbeatSeconds "([0-9]+)"\^\^xsd:integer ;\n {4}ciops:publishAgingSeconds "([0-9]+)"\^\^xsd:integer ;\n {4}ciops:reviewFixClassCap "([0-9]+)"\^\^xsd:integer \.\n\nciops:full-proof rdf:type ciops:AdmissionWorkKind ;\n {4}ciops:admissionTokenWeight "([0-9]+)"\^\^xsd:integer \.\n\nciops:merged-preview rdf:type ciops:AdmissionWorkKind ;\n {4}ciops:admissionTokenWeight "([0-9]+)"\^\^xsd:integer \.\n\nciops:review-fix rdf:type ciops:AdmissionWorkKind ;\n {4}ciops:admissionTokenWeight "([0-9]+)"\^\^xsd:integer \.\n\nciops:publish rdf:type ciops:AdmissionWorkKind ;\n {4}ciops:admissionTokenWeight "([0-9]+)"\^\^xsd:integer \.\n\nciops:AdmissionPriority-([a-z-]+) rdf:type ciops:AdmissionPriorityClass \.\nciops:AdmissionPriority-([a-z-]+) rdf:type ciops:AdmissionPriorityClass \.\n$/;

const schemaFailure = (message: string) => PolicyDecodeError.make({ message });

const captureAt = Effect.fnUntraced(function* (
  captures: RegExpMatchArray,
  index: number,
  label: string
): Effect.fn.Return<string, PolicyDecodeError> {
  return yield* pipe(
    A.get(captures, index),
    Effect.fromOption(() => schemaFailure(`Known-shape A-Box capture "${label}" was absent.`))
  );
});

const decodePositiveInteger = Effect.fnUntraced(function* (
  raw: string,
  label: string
): Effect.fn.Return<PosInt, PolicyDecodeError> {
  const finite = yield* FiniteFromString.decodeEffect(raw).pipe(
    Effect.mapError(() => schemaFailure(`A-Box value "${label}" was not a finite number.`))
  );
  return yield* PosInt.decodeEffect(finite).pipe(
    Effect.mapError(() => schemaFailure(`A-Box value "${label}" was not a positive integer.`))
  );
});

const decodePriority = Effect.fnUntraced(function* (
  raw: string
): Effect.fn.Return<AdmissionPriority, PolicyDecodeError> {
  return yield* AdmissionPriority.decodeUnknownEffect(raw).pipe(
    Effect.mapError(() => schemaFailure("A-Box declared an unknown admission priority."))
  );
});

/**
 * Decodes the complete committed Turtle document into admission policy data.
 *
 * **Details**
 *
 * The decoder accepts only the ratified S6 document shape. It extracts every
 * numeric value and priority from the supplied bytes, then schema-decodes the
 * captures; no policy value is supplied as a fallback.
 *
 * **Example** (Reject a partial A-Box)
 *
 * ```ts
 * import { decodeAdmissionPolicyParams } from "@/projection/AboxPolicy"
 * import { Effect } from "effect"
 * import * as Result from "effect/Result"
 *
 * const result = Effect.runSync(Effect.result(decodeAdmissionPolicyParams("ciops:partial")))
 * console.log(Result.isFailure(result)) // true
 * ```
 *
 * @category decoding
 * @since 0.0.0
 */
export const decodeAdmissionPolicyParams = Effect.fn("AboxPolicy.decodeAdmissionPolicyParams")(function* (
  source: string
): Effect.fn.Return<AdmissionPolicyParams, PolicyDecodeError> {
  const captures = yield* pipe(
    source,
    Str.match(knownAboxShape),
    Effect.fromOption(() => schemaFailure("Policy A-Box did not match the ratified S6 document shape."))
  );

  const values = yield* Effect.all(
    {
      capacityMaxTokens: decodePositiveInteger(yield* captureAt(captures, 1, "capacityMaxTokens"), "capacityMaxTokens"),
      slotSizeGib: decodePositiveInteger(yield* captureAt(captures, 2, "slotSizeGib"), "slotSizeGib"),
      reserveGib: decodePositiveInteger(yield* captureAt(captures, 3, "reserveGib"), "reserveGib"),
      hardFloorGib: decodePositiveInteger(yield* captureAt(captures, 4, "hardFloorGib"), "hardFloorGib"),
      heartbeatSeconds: decodePositiveInteger(yield* captureAt(captures, 5, "heartbeatSeconds"), "heartbeatSeconds"),
      publishAgingSeconds: decodePositiveInteger(
        yield* captureAt(captures, 6, "publishAgingSeconds"),
        "publishAgingSeconds"
      ),
      reviewFixClassCap: decodePositiveInteger(yield* captureAt(captures, 7, "reviewFixClassCap"), "reviewFixClassCap"),
      fullProof: decodePositiveInteger(yield* captureAt(captures, 8, "full-proof weight"), "full-proof weight"),
      mergedPreview: decodePositiveInteger(
        yield* captureAt(captures, 9, "merged-preview weight"),
        "merged-preview weight"
      ),
      reviewFix: decodePositiveInteger(yield* captureAt(captures, 10, "review-fix weight"), "review-fix weight"),
      publish: decodePositiveInteger(yield* captureAt(captures, 11, "publish weight"), "publish weight"),
      firstPriority: decodePriority(yield* captureAt(captures, 12, "first priority")),
      secondPriority: decodePriority(yield* captureAt(captures, 13, "second priority")),
    },
    { concurrency: "unbounded" }
  );

  return AdmissionPolicyParams.make({
    capacityMaxTokens: values.capacityMaxTokens,
    slotSizeGib: values.slotSizeGib,
    reserveGib: values.reserveGib,
    hardFloorGib: values.hardFloorGib,
    heartbeatSeconds: values.heartbeatSeconds,
    publishAgingSeconds: values.publishAgingSeconds,
    reviewFixClassCap: values.reviewFixClassCap,
    weights: AdmissionTokenWeights.make({
      fullProof: values.fullProof,
      mergedPreview: values.mergedPreview,
      reviewFix: values.reviewFix,
      publish: values.publish,
    }),
    priorityOrder: [values.firstPriority, values.secondPriority],
  });
});
