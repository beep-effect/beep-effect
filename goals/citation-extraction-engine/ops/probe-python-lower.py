#!/usr/bin/env python3
"""Freeze observed CPython lowercase mappings and contextual-sigma properties."""
import argparse
import base64
import ctypes
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import unicodedata

PIN = "04d82c032ad5fd0f9ab72a61c87110c46ee8f52e"
TREE = "a35a58fac03400f71a93a93485b77f1d56f2b02f"


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def ranges(points):
    result = []
    for point in points:
        if result and result[-1][1] + 1 == point:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def native(text):
    width = 1 if not text or max(map(ord, text)) <= 255 else 2 if max(map(ord, text)) <= 65535 else 4
    return {"width": width, "bytes": base64.b64encode(b"".join(ord(c).to_bytes(width, "little") for c in text)).decode(),
            "points": len(text), "utf16": len(text.encode("utf-16-le", "surrogatepass")) // 2}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oracle-root", required=True, type=Path)
    parser.add_argument("--data-output", required=True, type=Path)
    parser.add_argument("--cases-output", required=True, type=Path)
    parser.add_argument("--module-output", required=True, type=Path)
    args = parser.parse_args()
    root = args.oracle_root.resolve()
    git = lambda *values: subprocess.check_output(["git", "-C", str(root), *values], text=True).strip()
    if (git("rev-parse", "HEAD"), git("rev-parse", "HEAD^{tree}"), git("status", "--porcelain")) != (PIN, TREE, ""):
        raise SystemExit("oracle provenance mismatch")
    if sys.version_info[:3] != (3, 11, 15) or unicodedata.unidata_version != "14.0.0":
        raise SystemExit("Python/Unicode pin mismatch")
    # Read-only predicate observations from the pinned interpreter, independently
    # cross-checked against public lower/is* behavior at every Python code point.
    cased_api = ctypes.pythonapi._PyUnicode_IsCased
    ignored_api = ctypes.pythonapi._PyUnicode_IsCaseIgnorable
    for function in (cased_api, ignored_api):
        function.argtypes = [ctypes.c_uint32]
        function.restype = ctypes.c_int
    mappings, cased, ignored = [], [], []
    for point in range(0x110000):
        text = chr(point)
        lower = text.lower()
        if lower != text:
            mappings.append([point, list(map(ord, lower))])
        is_cased = bool(cased_api(point))
        is_ignored = bool(ignored_api(point))
        if is_cased != (text.islower() or text.isupper() or text.istitle()):
            raise SystemExit("cased observation mismatch")
        contextual = ("A\u03a3" + text + "A").lower()[1] == "\u03c3" and ("A\u03a3" + text + "!").lower()[1] == "\u03c2"
        if is_ignored != contextual:
            raise SystemExit("case-ignorable contextual observation mismatch")
        if is_cased:
            cased.append(point)
        if is_ignored:
            ignored.append(point)
    data = {"pythonVersion": "3.11.15", "unicodeVersion": "14.0.0", "lowerMappings": mappings,
            "casedRanges": ranges(cased), "caseIgnorableRanges": ranges(ignored)}
    texts = ["", "ABC abc", "\u0130I\u0131i", "\u212a\u017f", "\u03a3", "A\u03a3", "A\u03a3A", "\u03a3A",
             "A\u03a3\u0301", "A\u03a3\u0301A", "A\u03a3\u0301!", "A'\u03a3", "A\u03a3'A", "A\u03a3'!",
             "\U00010400\U00010428", "A\ud800\u03a3", "A\u03a3\ud800A", "\ud835\udfce\U0001d7ce",
             "\u1c89\U00010d50", "A\u03a3" + "\u0301" * 4096 + "A"]
    # Every non-identity one-point mapping also has a direct Python result case.
    texts.extend(chr(point) for point, _ in mappings)
    cases = [{"id": index, "source": native(text), "lower": native(text.lower())} for index, text in enumerate(texts)]
    raw_data = json.dumps(data, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    output = {"schemaVersion": "citation-python-lower-observations/v1", "oracleCommit": PIN, "oracleTree": TREE,
              "producerSha256": sha(Path(__file__).read_bytes()), "tokenizerSourceSha256": sha((root / "eyecite/tokenizers.py").read_bytes()),
              "data": data, "dataSha256": sha(raw_data.encode()), "allPoints": 0x110000,
              "casedPoints": len(cased), "caseIgnorablePoints": len(ignored), "cases": cases}
    header = '''/** Frozen observable CPython 3.11.15 / Unicode 14 lowercase facts.
 * Generated by goals/citation-extraction-engine/ops/probe-python-lower.py.
 * No interpreter implementation source is included.
 * @internal @packageDocumentation @since 0.0.0
 */
import { $LawPracticeServerId } from "@beep/identity/packages";
import * as S from "effect/Schema";
const $I = $LawPracticeServerId.create("internal/Citation/PythonCaseData");
const Point = S.Int.check(S.isBetween({ minimum: 0, maximum: 0x10ffff })).pipe(
  $I.annoteSchema("Point", { description: "Python Unicode storage word, including literal surrogates." })
);
const Range = S.Tuple([Point, Point]).pipe(
  $I.annoteSchema("Range", { description: "Inclusive interval in the frozen observed character set." })
);
/** @internal @category models @since 0.0.0 */
export class CitationPythonCaseData extends S.Opaque<CitationPythonCaseData, { readonly brand: unique symbol }>()(
  S.Struct({
    pythonVersion: S.tag("3.11.15"), unicodeVersion: S.tag("14.0.0"),
    lowerMappings: S.Array(S.Tuple([Point, S.NonEmptyArray(Point).check(S.isMaxLength(3))])).check(S.isBetweenLength(1433, 1433)),
    casedRanges: S.Array(Range).check(S.isBetweenLength(155, 155)),
    caseIgnorableRanges: S.Array(Range).check(S.isBetweenLength(427, 427)),
  }).pipe($I.annoteSchema("CitationPythonCaseData", { description: "Complete pinned lowercase mapping and contextual-sigma predicate observations." }))
) {}
/** @internal @category models @since 0.0.0 */
export const citationPythonCaseData = CitationPythonCaseData.make('''
    module_data = {key: value for key, value in data.items() if key not in ("pythonVersion", "unicodeVersion")}
    args.module_output.write_text(header + json.dumps(module_data, ensure_ascii=True, sort_keys=True, indent=2) + ");\n")
    args.data_output.write_text(raw_data + "\n")
    args.cases_output.write_text(json.dumps(output, ensure_ascii=True, sort_keys=True, indent=2) + "\n")
    print(json.dumps({"mappings": len(mappings), "cased": len(cased), "caseIgnorable": len(ignored), "cases": len(cases),
                      "dataSha256": output["dataSha256"]}))


if __name__ == "__main__":
    main()
