/** The brand every schema class carries (D4). */
export const BRAND = "{ readonly brand: unique symbol }";
/** Brand for schemas that already own a `brand` field (the default key would collapse the type to `never`). */
export const BRAND_ALT = "{ readonly nominal: unique symbol }";
const EFFECTED_PREFIX = "scratchpad/effected/";
const EFFECTED_TEST = /^scratchpad\/test\/([^/]+?)(?:\/|\.test\.tsx?$)/;

/**
 * The verbatim effected port (D6): its sources under `scratchpad/effected/<module>/` and the
 * upstream tests copied beside them, `scratchpad/test/<module>/**` and `scratchpad/test/<module>.test.ts`,
 * for every `<module>` that has a source directory. Other `scratchpad/test` files stay in scope.
 */
const effectedPortMatcher = (files: ReadonlyArray<string>): ((file: string) => boolean) => {
  const modules = new Set<string>();
  for (const file of files) {
    if (!file.startsWith(EFFECTED_PREFIX)) continue;
    const segments = file.slice(EFFECTED_PREFIX.length).split("/");
    if (segments.length > 1 && segments[0] !== undefined) modules.add(segments[0]);
  }
  return (file) => {
    if (file.startsWith(EFFECTED_PREFIX)) return true;
    const module = EFFECTED_TEST.exec(file)?.[1];
    return module !== undefined && modules.has(module);
  };
};
const GENERATED_HEADER =
  /(@generated|auto-?generated|this file (is|was) (auto-?)?generated|code generated|generated by|do not edit)/i;
const DECLARATION_HOOK_KEY = /^to[A-Z]/;

export type SchemaKind = "Class" | "TaggedClass" | "Error" | "TaggedError" | "Opaque";
const SCHEMA_KINDS: ReadonlySet<string> = new Set<SchemaKind>([
  "Class",
  "TaggedClass",
  "Error",
  "TaggedError",
  "Opaque",
]);

export type KeepReason =
  | "effected-port"
  | "instance-member"
  | "static-super"
  | "named-import"
  | "extend-root"
  | "subclassed"
  | "instanceof"
  | "new-site"
  | "keep-class-allowlist"
  | "fields-expression-unknown"
  | "tagged-struct-source"
  | "declaration-hooks"
  | "tag-field"
  | "brand-override-exception"
  | "unrecognized-shape";

type RefKind = "extend" | "subclass" | "instanceof" | "new" | "instanceOf-schema";

const REF_REASON: Record<RefKind, KeepReason> = {
  extend: "extend-root",
  subclass: "subclassed",
  instanceof: "instanceof",
  new: "new-site",
  "instanceOf-schema": "instanceof",
};

/** True when the leading comment block marks the file as generated. */
export const isGeneratedSource = (text: string): boolean => {
  const head = text.slice(0, 800);
  const leading = /^(\s*(\/\/[^\n]*\n|\/\*[\s\S]*?\*\/))+/.exec(head)?.[0] ?? "";
  return GENERATED_HEADER.test(leading);
};

