const hasModifier = (node: ts.Node, kind: ts.SyntaxKind): boolean =>
  (ts.canHaveModifiers(node) ? (ts.getModifiers(node) ?? []) : []).some((modifier) => modifier.kind === kind);

const hasInstanceMember = (node: ts.ClassLikeDeclaration): boolean =>
  node.members.some((member) => {
    if (ts.isSemicolonClassElement(member) || ts.isClassStaticBlockDeclaration(member)) return false;
    if (ts.isConstructorDeclaration(member) || ts.isIndexSignatureDeclaration(member)) return true;
    return !hasModifier(member, ts.SyntaxKind.StaticKeyword);
  });

/**
 * A static member that reads `super` (`static override make(...) { return super.make(...) }`).
 * Schema objects memoize `make` / `makeEffect` / `makeOption` through prototype getters that
 * `defineProperty` onto `this`, so on an `S.Opaque` the first `super.make` call replaces the
 * override with the base parser and every later call skips it. `S.Class` statics are safe.
 */
const hasStaticSuperMember = (node: ts.ClassLikeDeclaration): boolean =>
  node.members.some((member) => {
    if (!hasModifier(member, ts.SyntaxKind.StaticKeyword)) return false;
    let found = false;
    const visit = (child: ts.Node): void => {
      if (found) return;
      if (child.kind === ts.SyntaxKind.SuperKeyword) {
        found = true;
        return;
      }
      ts.forEachChild(child, visit);
    };
    ts.forEachChild(member, visit);
    return found;
  });

/** `$I.annote(...)` / `$I.annoteClass(...)` → the composer expression text. */
const identityAnnoteCall = (expression: ts.Expression): ts.CallExpression | undefined =>
  ts.isCallExpression(expression) &&
  ts.isPropertyAccessExpression(expression.expression) &&
  (expression.expression.name.text === "annote" || expression.expression.name.text === "annoteClass")
    ? expression
    : undefined;

/** `$I\`Name\`` → `{ composer: "$I", name: "Name" }`. */
const identityTemplate = (expression: ts.Expression | undefined): { composer: string; name: string } | undefined =>
  expression !== undefined &&
  ts.isTaggedTemplateExpression(expression) &&
  ts.isNoSubstitutionTemplateLiteral(expression.template)
    ? { composer: expression.tag.getText(), name: expression.template.text }
    : undefined;

const objectHasDeclarationHook = (expression: ts.Expression | undefined): boolean =>
  expression !== undefined &&
  ts.isObjectLiteralExpression(expression) &&
  expression.properties.some(
    (property) =>
      property.name !== undefined &&
      (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
      DECLARATION_HOOK_KEY.test(property.name.text)
  );

const objectHasKey = (expression: ts.ObjectLiteralExpression, key: string): boolean =>
  expression.properties.some(
    (property) =>
      property.name !== undefined &&
      (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
      property.name.text === key
  );

type FieldsShape = "fields" | "struct" | "unknown";

/** Classifies the Class `schema` argument: a fields record, a Struct schema, or unknown. */
/** Repo-wide file lookup; lets field classification follow relative imports. */
type FileIndex = ReadonlyMap<string, FileInfo>;

const findConstInitializer = (info: FileInfo, name: string): ts.Expression | undefined => {
  for (const statement of info.sf.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (
        ts.isIdentifier(declaration.name) &&
        declaration.name.text === name &&
        declaration.initializer !== undefined
      ) {
        return declaration.initializer;
      }
    }
  }
  return undefined;
};

const resolveRelativeFile = (index: FileIndex, from: string, spec: string): FileInfo | undefined => {
  if (!spec.startsWith(".")) return undefined;
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec)).replace(/\.(js|mjs)$/, "");
  for (const suffix of RESOLVE_SUFFIXES) {
    const target = index.get(`${base}${suffix}`);
    if (target !== undefined) return target;
  }
  return undefined;
};

/**
 * Classifies the Class `schema` argument: a fields record, a Struct schema, or
 * unknown. Follows local consts, relative imports, `.check`/`.annotate` chains.
 */
const classifyFields = (index: FileIndex, info: FileInfo, expression: ts.Expression, depth = 0): FieldsShape => {
  if (depth > 8) return "unknown";
  const recurse = (next: ts.Expression, owner: FileInfo = info) => classifyFields(index, owner, next, depth + 1);
  if (ts.isObjectLiteralExpression(expression)) return "fields";
  if (
    ts.isParenthesizedExpression(expression) ||
    ts.isSatisfiesExpression(expression) ||
    ts.isAsExpression(expression)
  ) {
    return recurse(expression.expression);
  }
  if (ts.isPropertyAccessExpression(expression) && expression.name.text === "fields") return "fields";
  if (ts.isCallExpression(expression)) {
    const callee = expression.expression;
    if (!ts.isPropertyAccessExpression(callee)) return "unknown";
    const calleeName = callee.name.text;
    if (
      (calleeName === "Struct" || calleeName === "TaggedStruct") &&
      info.nsBindings.has(callee.expression.getText())
    ) {
      return "struct";
    }
    if (calleeName === "mapFields") return "struct";
    if (calleeName === "check" || calleeName === "annotate") {
      return recurse(callee.expression) === "struct" ? "struct" : "unknown";
    }
    return "unknown";
  }
  if (ts.isIdentifier(expression)) {
    const local = findConstInitializer(info, expression.text);
    if (local !== undefined) return recurse(local);
    const binding = info.imports.get(expression.text);
    if (binding === undefined || binding.imported === "*" || binding.imported === "default") return "unknown";
    const target = resolveRelativeFile(index, info.file, binding.spec);
    const init = target === undefined ? undefined : findConstInitializer(target, binding.imported);
    return target !== undefined && init !== undefined ? recurse(init, target) : "unknown";
  }
  return "unknown";
};

interface ConversionPlan {
  readonly edits: ReadonlyArray<Edit>;
  readonly outcome: Outcome;
}

/** Comment texts inside `[start, end)`, skipping the spans of `kept` nodes (re-emitted verbatim elsewhere). */
const commentsIn = (text: string, start: number, end: number, kept: ReadonlyArray<ts.Node>): ReadonlyArray<string> => {
  const scanner = ts.createScanner(ts.ScriptTarget.Latest, false, ts.LanguageVariant.Standard, text);
  scanner.resetTokenState(start);
  const out: Array<string> = [];
  while (scanner.getTokenEnd() < end) {
    const token = scanner.scan();
    if (token === ts.SyntaxKind.EndOfFileToken) break;
    const tokenStart = scanner.getTokenStart();
    if (tokenStart >= end) break;
    const insideKept = kept.some((node) => tokenStart >= node.pos && tokenStart < node.end);
    if (insideKept) {
      const owner = kept.find((node) => tokenStart >= node.pos && tokenStart < node.end);
      if (owner !== undefined && tokenStart >= owner.getStart()) {
        scanner.resetTokenState(owner.end);
        continue;
      }
    }
    if (token === ts.SyntaxKind.SingleLineCommentTrivia || token === ts.SyntaxKind.MultiLineCommentTrivia) {
      out.push(scanner.getTokenText());
    }
  }
  return out;
};

/** Plans the Class/TaggedClass → Opaque conversion, or a keep reason when the shape is not convertible. */
const planConversion = (
  index: FileIndex,
  info: FileInfo,
  decl: SchemaClassDecl,
  override: string | undefined = undefined
): ConversionPlan | KeepReason => {
  const { heritage } = decl;
  const { ns, inner, outer } = heritage;
  const self = heritage.typeArgs[0];
  if (self === undefined) return "unrecognized-shape";
  const id = inner.arguments[0];
  const args = outer.arguments;
  const isTagged = heritage.kind === "TaggedClass";
  const tag = isTagged ? args[0] : undefined;
  const fields = isTagged ? args[1] : args[0];
  const annot = isTagged ? args[2] : args[1];
  if (fields === undefined || (isTagged && tag === undefined) || (!isTagged && id === undefined)) {
    return "unrecognized-shape";
  }
  if (args.length > (isTagged ? 3 : 2) || inner.arguments.length > 1) return "unrecognized-shape";
  const shape = classifyFields(index, info, fields);
  if (shape === "unknown") return "fields-expression-unknown";
  if (isTagged && shape === "struct") return "tagged-struct-source";

  // A literal `_tag` field on a plain Class becomes a TaggedStruct source (`schemaStructWithTag`).
  const tagField =
    !isTagged && ts.isObjectLiteralExpression(fields)
      ? fields.properties.find(
          (property) =>
            property.name !== undefined &&
            (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
            property.name.text === "_tag"
        )
      : undefined;
  const promotedTag = tagField === undefined ? undefined : literalTagOf(info, tagField);
  if (tagField !== undefined && promotedTag === undefined) return "tag-field";

  const annoteCall = annot === undefined ? undefined : identityAnnoteCall(annot);
  if (objectHasDeclarationHook(annot) || objectHasDeclarationHook(annoteCall?.arguments[1])) {
    return "declaration-hooks";
  }

  const text = info.text;
  const sliceOf = (node: ts.Node): string => text.slice(node.getStart(info.sf), node.end);
  const idText = id !== undefined ? sliceOf(id) : sliceOf(tag as ts.Expression);
  const template = identityTemplate(id);

  // A module identity composer (`const $I = $PkgId.create(...)`) makes the identity annotation the
  // spelling the schema-first lint expects; the identifier becomes `$I/<ClassName>`.
  const composer = template?.composer ?? identityComposerOf(info);
  let suffix: string;
  if (annoteCall !== undefined) {
    const callee = annoteCall.expression as ts.PropertyAccessExpression;
    const argsText = text.slice(annoteCall.arguments.pos, annoteCall.arguments.end);
    suffix = `.pipe(${sliceOf(callee.expression)}.annoteSchema(${argsText}))`;
  } else if (annot === undefined) {
    suffix =
      template !== undefined
        ? `.pipe(${template.composer}.annoteSchema(${JSON.stringify(template.name)}))`
        : composer !== undefined
          ? `.pipe(${composer}.annoteSchema(${JSON.stringify(decl.name)}))`
          : `.annotate({ identifier: ${idText} })`;
  } else if (ts.isObjectLiteralExpression(annot)) {
    const body = text.slice(annot.properties.pos, annot.properties.end).trim().replace(/,\s*$/, "");
    if (objectHasKey(annot, "identifier")) {
      suffix = `.annotate(${sliceOf(annot)})`;
    } else if (composer !== undefined) {
      const name = JSON.stringify(template?.name ?? decl.name);
      suffix =
        body.length === 0
          ? `.pipe(${composer}.annoteSchema(${name}))`
          : `.pipe(${composer}.annoteSchema(${name}, { ${body} }))`;
    } else {
      suffix =
        body.length === 0 ? `.annotate({ identifier: ${idText} })` : `.annotate({ identifier: ${idText}, ${body} })`;
    }
  } else {
    // Two annotate calls keep the class precedence (ANNOT overrides the class identifier).
    suffix = `.annotate({ identifier: ${idText} }).annotate(${sliceOf(annot)})`;
  }

  const head = `${ns}.Opaque<${sliceOf(self)}, ${brandFor(index, info, decl, override)}>()(`;
  const outerStart = outer.getStart(info.sf);
  const sourceStart = isTagged ? (tag as ts.Expression).getStart(info.sf) : fields.getStart(info.sf);
  const sourceOpen =
    shape === "struct"
      ? ""
      : isTagged
        ? `${ns}.TaggedStruct(`
        : promotedTag !== undefined
          ? `${ns}.TaggedStruct(${promotedTag}, `
          : `${ns}.Struct(`;
  const sourceClose = shape === "struct" ? "" : ")";
  // Comments in the dropped spans move next to the emitted code instead of vanishing.
  const headComments = commentsIn(text, outerStart, sourceStart, id === undefined ? [] : [id]);
  const tailComments = commentsIn(text, fields.end, outer.end, annot === undefined ? [] : [annot]);
  const headPrefix = headComments.length === 0 ? "" : `${headComments.join("\n")}\n`;
  const tailInfix = tailComments.length === 0 ? "" : `\n${tailComments.join("\n")}\n`;
  return {
    outcome: isTagged ? "converted-tagged-class" : "converted-class",
    edits: [
      { start: outerStart, end: sourceStart, text: `${headPrefix}${head}${sourceOpen}` },
      { start: fields.end, end: outer.end, text: `${sourceClose}${tailInfix}${suffix})` },
      ...(tagField === undefined ? [] : [removeProperty(text, info.sf, tagField)]),
    ],
  };
};

/** `_tag: NS.tag("X")` / `_tag: NS.Literal("X")` → the literal text `"X"`. */
const literalTagOf = (info: FileInfo, property: ts.ObjectLiteralElementLike): string | undefined => {
  if (!ts.isPropertyAssignment(property) || !ts.isCallExpression(property.initializer)) return undefined;
  const call = property.initializer;
  const callee = call.expression;
  const literal = call.arguments[0];
  if (!ts.isPropertyAccessExpression(callee) || !info.nsBindings.has(callee.expression.getText())) return undefined;
  if (callee.name.text !== "tag" && callee.name.text !== "Literal") return undefined;
  if (call.arguments.length !== 1 || literal === undefined || !ts.isStringLiteral(literal)) return undefined;
  return literal.getText(info.sf);
};

/** Deletes an object-literal property and its trailing comma. */
const removeProperty = (text: string, sf: ts.SourceFile, property: ts.ObjectLiteralElementLike): Edit => {
  const start = property.getStart(sf);
  let end = property.end;
  const rest = /^\s*,/.exec(text.slice(end));
  if (rest !== null) end += rest[0].length;
  return { start, end, text: "" };
};

/** Brand insertion after the first type argument. */
const planBrand = (
  index: FileIndex,
  info: FileInfo,
  decl: SchemaClassDecl,
  override: string | undefined = undefined
): ReadonlyArray<Edit> | Outcome => {
  const { typeArgs } = decl.heritage;
  if (typeArgs.length >= 2) return "already-branded";
  const self = typeArgs[0];
  if (self === undefined) return "skipped-no-self-type";
  return [{ start: self.end, end: self.end, text: `, ${brandFor(index, info, decl, override)}` }];
};

/** True when a fields record (or the Struct built from it) declares a `brand` key. */
const fieldsHaveBrandKey = (index: FileIndex, info: FileInfo, expression: ts.Expression, depth = 0): boolean => {
  if (depth > 8) return false;
  const recurse = (next: ts.Expression, owner: FileInfo = info) => fieldsHaveBrandKey(index, owner, next, depth + 1);
  if (ts.isObjectLiteralExpression(expression)) {
    return expression.properties.some(
      (property) =>
        property.name !== undefined &&
        (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
        property.name.text === "brand"
    );
  }
  if (
    ts.isParenthesizedExpression(expression) ||
    ts.isSatisfiesExpression(expression) ||
    ts.isAsExpression(expression)
  ) {
    return recurse(expression.expression);
  }
  if (ts.isCallExpression(expression)) {
    const callee = expression.expression;
    if (!ts.isPropertyAccessExpression(callee)) return false;
    const name = callee.name.text;
    const fields =
      name === "TaggedStruct" ? expression.arguments[1] : name === "Struct" ? expression.arguments[0] : undefined;
    if (fields !== undefined) return recurse(fields);
    return recurse(callee.expression);
  }
  if (ts.isIdentifier(expression)) {
    const local = findConstInitializer(info, expression.text);
    if (local !== undefined) return recurse(local);
    const binding = info.imports.get(expression.text);
    if (binding === undefined || binding.imported === "*" || binding.imported === "default") return false;
    const target = resolveRelativeFile(index, info.file, binding.spec);
    const init = target === undefined ? undefined : findConstInitializer(target, binding.imported);
    return target !== undefined && init !== undefined && recurse(init, target);
  }
  return false;
};

/** The brand type argument for a declaration: {@link BRAND}, or {@link BRAND_ALT} when a `brand` field exists. */
const brandFor = (index: FileIndex, info: FileInfo, decl: SchemaClassDecl, override?: string): string => {
  if (override !== undefined) return override;
  const { kind, outer } = decl.heritage;
  const fields = kind === "TaggedClass" || kind === "TaggedError" ? outer.arguments[1] : outer.arguments[0];
  return fields !== undefined && fieldsHaveBrandKey(index, info, fields) ? BRAND_ALT : BRAND;
};

/**
 * Reverse of {@link planConversion}: `NS.Opaque<X, B>()(NS.Struct(F)<annotation>)` →
 * `NS.Class<X, B>(ID)(F[, ANNOT])` (and `TaggedStruct` → `TaggedClass`). Only the
 * exact shapes the forward transform emits are recognised.
 */
const planReverse = (info: FileInfo, decl: SchemaClassDecl): ConversionPlan | undefined => {
  const { heritage } = decl;
  const { ns, outer } = heritage;
  if (heritage.kind !== "Opaque" || heritage.typeArgs.length !== 2) return undefined;
  const self = heritage.typeArgs[0] as ts.TypeNode;
  const brand = heritage.typeArgs[1] as ts.TypeNode;
  const source = outer.arguments[0];
  if (source === undefined || outer.arguments.length !== 1 || !ts.isCallExpression(source)) return undefined;
  const sliceOf = (node: ts.Node): string => info.text.slice(node.getStart(info.sf), node.end);

  // source = BASE.pipe(C.annoteSchema(args)) | BASE.annotate({...})
  const method = source.expression;
  if (!ts.isPropertyAccessExpression(method) || !ts.isCallExpression(method.expression)) return undefined;
  const base = method.expression;
  const baseCallee = base.expression;
  if (!ts.isPropertyAccessExpression(baseCallee) || baseCallee.expression.getText() !== ns) return undefined;
  const isTagged = baseCallee.name.text === "TaggedStruct";
  if (!isTagged && baseCallee.name.text !== "Struct") return undefined;
  const fields = isTagged ? base.arguments[1] : base.arguments[0];
  const tag = isTagged ? base.arguments[0] : undefined;
  if (fields === undefined || base.arguments.length !== (isTagged ? 2 : 1)) return undefined;
  const annotationArg = source.arguments[0];
  if (annotationArg === undefined || source.arguments.length !== 1) return undefined;

  let idText: string | undefined;
  let annotText: string | undefined;
  if (method.name.text === "pipe" && ts.isCallExpression(annotationArg)) {
    const annoteSchema = annotationArg.expression;
    if (!ts.isPropertyAccessExpression(annoteSchema) || annoteSchema.name.text !== "annoteSchema") return undefined;
    const composer = sliceOf(annoteSchema.expression);
    const first = annotationArg.arguments[0];
    if (first === undefined || !ts.isStringLiteral(first)) return undefined;
    idText = `${composer}\`${first.text}\``;
    annotText = `${composer}.annote(${info.text.slice(annotationArg.arguments.pos, annotationArg.arguments.end)})`;
  } else if (method.name.text === "annotate" && ts.isObjectLiteralExpression(annotationArg)) {
    const identifier = annotationArg.properties.find(
      (property) =>
        ts.isPropertyAssignment(property) && ts.isIdentifier(property.name) && property.name.text === "identifier"
    );
    if (identifier === undefined || !ts.isPropertyAssignment(identifier)) return undefined;
    idText = sliceOf(identifier.initializer);
    const rest = annotationArg.properties.filter((property) => property !== identifier).map(sliceOf);
    annotText = rest.length === 0 ? undefined : `{ ${rest.join(", ")} }`;
  } else {
    return undefined;
  }

  const tagText = tag === undefined ? undefined : sliceOf(tag);
  const innerId = isTagged && idText === tagText ? "" : idText;
  const head = `${ns}.${isTagged ? "TaggedClass" : "Class"}<${sliceOf(self)}, ${sliceOf(brand)}>(${innerId})(`;
  const argsText = [tagText, sliceOf(fields), annotText].filter((part) => part !== undefined).join(", ");
  return {
    outcome: "reverted-to-class",
    edits: [{ start: outer.getStart(info.sf), end: outer.end, text: `${head}${argsText})` }],
  };
};

const applyEdits = (text: string, edits: ReadonlyArray<Edit>): string => {
  const sorted = [...edits].sort((left, right) => right.start - left.start);
  let out = text;
  for (const edit of sorted) out = `${out.slice(0, edit.start)}${edit.text}${out.slice(edit.end)}`;
  return out;
};

export const familyOf = (file: string): string => {
  const parts = file.split("/");
  if (parts[0] === "packages" && parts.length > 2) return `packages/${parts[1]}`;
  return parts[0] ?? file;
};

/** The module's identity composer binding: a top-level `const $X = <expr>.create(...)` or an imported `$I`. */
const identityComposerOf = (info: FileInfo): string | undefined => {
  for (const statement of info.sf.statements) {
    if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        const init = declaration.initializer;
        if (
          ts.isIdentifier(declaration.name) &&
          declaration.name.text.startsWith("$") &&
          init !== undefined &&
          ts.isCallExpression(init) &&
          ts.isPropertyAccessExpression(init.expression) &&
          init.expression.name.text === "create"
        ) {
          return declaration.name.text;
        }
      }
    }
  }
  const imported = info.imports.get("$I");
  return imported !== undefined && imported.imported !== "*" ? "$I" : undefined;
};

/**
 * Normalizes a forward-shaped `S.Opaque<X, B>()(SOURCE.annotate({ identifier: ID, ...rest }))` to
 * `.pipe($I.annoteSchema("X", { ...rest }))` when the module has an identity composer.
 */
const planIdentityNormalize = (info: FileInfo, decl: SchemaClassDecl): ReadonlyArray<Edit> => {
  const { heritage } = decl;
  if (heritage.kind !== "Opaque" || heritage.typeArgs.length !== 2 || decl.name === undefined) return [];
  const composer = identityComposerOf(info);
  const source = heritage.outer.arguments[0];
  if (composer === undefined || source === undefined || heritage.outer.arguments.length !== 1) return [];
  if (!ts.isCallExpression(source) || !ts.isPropertyAccessExpression(source.expression)) return [];
  if (source.expression.name.text !== "annotate" || source.arguments.length !== 1) return [];
  const literal = source.arguments[0];
  if (literal === undefined || !ts.isObjectLiteralExpression(literal)) return [];
  const identifier = literal.properties.find(
    (property) =>
      ts.isPropertyAssignment(property) && ts.isIdentifier(property.name) && property.name.text === "identifier"
  );
  if (identifier === undefined) return [];
  if (objectHasDeclarationHook(literal)) return [];
  const rest = literal.properties
    .filter((property) => property !== identifier)
    .map((property) => property.getText(info.sf));
  const name = JSON.stringify(decl.name);
  const call =
    rest.length === 0
      ? `${composer}.annoteSchema(${name})`
      : `${composer}.annoteSchema(${name}, { ${rest.join(", ")} })`;
  return [{ start: source.expression.name.getStart(info.sf), end: source.end, text: `pipe(${call})` }];
};

/** Names with a top-level `declare namespace N { ... Type ... }` (hand-written decoded types). */
const declaredNamespaces = (info: FileInfo): ReadonlySet<string> => {
  const names = new Set<string>();
  for (const statement of info.sf.statements) {
    if (!ts.isModuleDeclaration(statement) || !ts.isIdentifier(statement.name)) continue;
    const body = statement.body;
    if (body === undefined || !ts.isModuleBlock(body)) continue;
    const declaresType = body.statements.some(
      (member) =>
        (ts.isInterfaceDeclaration(member) || ts.isTypeAliasDeclaration(member)) && member.name.text === "Type"
    );
    if (declaresType) names.add(statement.name.text);
  }
  return names;
};

/** `new X(` → `X.make(` inside JSDoc comments, for names that end up as `S.Opaque` in the file's package. */
const docExampleEdits = (info: FileInfo, isOpaqueIn: (file: string, name: string) => boolean): ReadonlyArray<Edit> => {
  const seen = new Set<number>();
  const edits: Array<Edit> = [];
  const visit = (node: ts.Node): void => {
    for (const range of ts.getLeadingCommentRanges(info.text, node.getFullStart()) ?? []) {
      if (seen.has(range.pos)) continue;
      seen.add(range.pos);
      const comment = info.text.slice(range.pos, range.end);
      if (!comment.startsWith("/**")) continue;
      for (const match of comment.matchAll(/\bnew ([A-Z][A-Za-z0-9_]*)\(/g)) {
        const name = match[1] ?? "";
        if (!isOpaqueIn(info.file, name)) continue;
        const at = range.pos + (match.index ?? 0);
        edits.push({ start: at, end: at + match[0].length, text: `${name}.make(` });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(info.sf);
  return edits;
};

