/** One `keep-class.jsonc` entry. */
export interface KeepEntry {
  /**
   * `"structural"`: a documented schema-first exception (D4) - the class keeps its
   * computed shape but carries the structural `{}` brand, because hand-written
   * namespace `Type` declarations (needed for recursion) must stay structurally
   * equal to it. Such entries never force class semantics.
   * `"alternate"`: the class carries {@link BRAND_ALT} instead, for schemas whose type is
   * intersected with another branded schema (two `brand: unique symbol` keys reduce the
   * intersection to `never`).
   */
  readonly brand?: "structural" | "alternate" | undefined;
  /** Class name, or `*` (with `brand: "structural"`) for every class of the file that has a declared namespace `Type`. */
  readonly class: string;
  readonly file: string;
  readonly reason: string;
}

