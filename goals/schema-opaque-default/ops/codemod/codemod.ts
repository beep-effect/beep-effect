interface ImportBinding {
  /** Exported name, or `*` for a namespace import. */
  readonly imported: string;
  readonly spec: string;
}

interface SchemaHeritage {
  /** `S.Class<X>(ID)` inner call. */
  readonly inner: ts.CallExpression;
  readonly kind: SchemaKind;
  /** Text of the Schema namespace expression (`S`, `Schema`, `Effect.Schema`); `""` for a named import. */
  readonly ns: string;
  /** `S.Class<X>(ID)(ARGS)` outer call. */
  readonly outer: ts.CallExpression;
  readonly typeArgs: ReadonlyArray<ts.TypeNode>;
}

interface SchemaClassDecl {
  readonly file: string;
  readonly heritage: SchemaHeritage;
  readonly line: number;
  readonly name: string | undefined;
  readonly node: ts.ClassLikeDeclaration;
}

interface Ref {
  readonly kind: RefKind;
  readonly name: string;
  readonly qualifier: string | undefined;
  readonly site: string;
}

interface FileInfo {
  readonly declNames: ReadonlySet<string>;
  readonly decls: ReadonlyArray<SchemaClassDecl>;
  readonly file: string;
  readonly generated: boolean;
  readonly imports: ReadonlyMap<string, ImportBinding>;
  readonly nsBindings: ReadonlySet<string>;
  readonly refs: ReadonlyArray<Ref>;
  readonly sf: ts.SourceFile;
  readonly text: string;
}

const lineOf = (sf: ts.SourceFile, pos: number): number => sf.getLineAndCharacterOfPosition(pos).line + 1;

const isSchemaModuleSpec = (spec: string): boolean => spec === "effect/Schema" || /\/Schema(\.ts)?$/.test(spec);

const collectImports = (
  sf: ts.SourceFile
): { imports: Map<string, ImportBinding>; ns: Set<string>; named: Map<string, SchemaKind> } => {
  const imports = new Map<string, ImportBinding>();
  const ns = new Set<string>();
  // `import { TaggedError } from "effect/Schema"`: local name → schema-class constructor.
  const named = new Map<string, SchemaKind>();
  for (const statement of sf.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const spec = statement.moduleSpecifier.text;
    const clause = statement.importClause;
    if (clause === undefined) continue;
    if (clause.name !== undefined) imports.set(clause.name.text, { spec, imported: "default" });
    const bindings = clause.namedBindings;
    if (bindings === undefined) continue;
    if (ts.isNamespaceImport(bindings)) {
      imports.set(bindings.name.text, { spec, imported: "*" });
      if (isSchemaModuleSpec(spec)) ns.add(bindings.name.text);
      if (spec === "effect") ns.add(`${bindings.name.text}.Schema`);
    } else {
      for (const element of bindings.elements) {
        const imported = (element.propertyName ?? element.name).text;
        imports.set(element.name.text, { spec, imported });
        if (spec === "effect" && imported === "Schema") ns.add(element.name.text);
        if (isSchemaModuleSpec(spec) && SCHEMA_KINDS.has(imported))
          named.set(element.name.text, imported as SchemaKind);
      }
    }
  }
  // Dynamic `import("effect/Schema")` modules bound to a conventional name.
  if (/import\(\s*["']effect\/Schema["']\s*\)/.test(sf.text)) {
    for (const name of ["S", "Schema", "SchemaModule"]) ns.add(name);
  }
  return { imports, ns, named };
};

const matchSchemaHeritage = (
  expression: ts.Expression,
  ns: ReadonlySet<string>,
  named: ReadonlyMap<string, SchemaKind>
): SchemaHeritage | undefined => {
  if (!ts.isCallExpression(expression)) return undefined;
  const inner = expression.expression;
  if (!ts.isCallExpression(inner)) return undefined;
  const callee = inner.expression;
  if (ts.isIdentifier(callee)) {
    const kind = named.get(callee.text);
    return kind === undefined
      ? undefined
      : { kind, ns: "", outer: expression, inner, typeArgs: inner.typeArguments ?? [] };
  }
  if (!ts.isPropertyAccessExpression(callee)) return undefined;
  const kind = callee.name.text;
  if (!SCHEMA_KINDS.has(kind)) return undefined;
  const nsText = callee.expression.getText();
  if (!ns.has(nsText)) return undefined;
  return { kind: kind as SchemaKind, ns: nsText, outer: expression, inner, typeArgs: inner.typeArguments ?? [] };
};

const heritageExpression = (node: ts.ClassLikeDeclaration): ts.Expression | undefined => {
  for (const clause of node.heritageClauses ?? []) {
    if (clause.token === ts.SyntaxKind.ExtendsKeyword) return clause.types[0]?.expression;
  }
  return undefined;
};

/** Splits `A.B.C` into `{ qualifier: "A.B", name: "C" }`; identifiers have no qualifier. */
const refTarget = (expression: ts.Expression): { name: string; qualifier: string | undefined } | undefined => {
  if (ts.isIdentifier(expression)) return { name: expression.text, qualifier: undefined };
  if (ts.isPropertyAccessExpression(expression) && ts.isIdentifier(expression.name)) {
    return { name: expression.name.text, qualifier: expression.expression.getText() };
  }
  return undefined;
};

const scanFile = (file: string, text: string): FileInfo => {
  const sf = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS
  );
  const { imports, ns, named } = collectImports(sf);
  const decls: Array<SchemaClassDecl> = [];
  const declNames = new Set<string>();
  const refs: Array<Ref> = [];
  const site = (node: ts.Node): string => `${file}:${lineOf(sf, node.getStart(sf))}`;
  const addRef = (kind: RefKind, expression: ts.Expression, at: ts.Node): void => {
    const target = refTarget(expression);
    if (target !== undefined) refs.push({ kind, ...target, site: site(at) });
  };

  const visit = (node: ts.Node): void => {
    if (ts.isClassDeclaration(node) || ts.isClassExpression(node)) {
      const expression = heritageExpression(node);
      if (expression !== undefined) {
        const heritage = matchSchemaHeritage(expression, ns, named);
        if (heritage !== undefined) {
          const name = node.name?.text;
          if (name !== undefined) declNames.add(name);
          decls.push({ file, name, node, heritage, line: lineOf(sf, node.getStart(sf)) });
        } else {
          // `class Y extends X.extend<Y>(...)(...)` or `class Y extends X`
          let base: ts.Expression = expression;
          while (ts.isCallExpression(base)) base = base.expression;
          if (ts.isPropertyAccessExpression(base) && base.name.text === "extend") {
            addRef("extend", base.expression, node);
          } else if (ts.isIdentifier(base) || ts.isPropertyAccessExpression(base)) {
            if (base === expression) addRef("subclass", base, node);
          }
        }
      }
    } else if (ts.isPropertyAccessExpression(node) && node.name.text === "extend") {
      const parent = node.parent;
      const isClassHeritage =
        ts.isCallExpression(parent) &&
        ts.isCallExpression(parent.parent) &&
        ts.isExpressionWithTypeArguments(parent.parent.parent);
      if (ts.isCallExpression(parent) && parent.expression === node && !isClassHeritage) {
        addRef("extend", node.expression, node);
      }
    } else if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.InstanceOfKeyword) {
      addRef("instanceof", node.right, node);
    } else if (ts.isNewExpression(node)) {
      addRef("new", node.expression, node);
    } else if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      node.expression.name.text === "instanceOf" &&
      ns.has(node.expression.expression.getText()) &&
      node.arguments[0] !== undefined
    ) {
      addRef("instanceOf-schema", node.arguments[0], node);
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);

  return { file, text, sf, generated: isGeneratedSource(text), nsBindings: ns, imports, decls, declNames, refs };
};

