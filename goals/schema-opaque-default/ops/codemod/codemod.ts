/** Inputs for one codemod pass over an in-memory source set. */
export interface CodemodInput {
  /** Files whose edits are applied (the index always spans every source). */
  readonly inScope: (file: string) => boolean;
  readonly keepClass: ReadonlyArray<KeepEntry>;
  /** Workspace package name → repo-relative package directory. */
  readonly packageDirs: ReadonlyMap<string, string>;
  /** Reverse D1: forward-shaped `S.Opaque` back to `S.Class`/`S.TaggedClass`. */
  readonly reverse: boolean;
  readonly sources: ReadonlyArray<{ readonly file: string; readonly text: string }>;
}

/** Result of one codemod pass. */
export interface CodemodResult {
  readonly newSites: ReadonlyArray<{ readonly target: string; readonly site: string }>;
  readonly opaqueWithKeepReasons: ReadonlyArray<string>;
  readonly outputs: ReadonlyArray<{ readonly file: string; readonly text: string }>;
  readonly results: ReadonlyArray<DeclResult>;
}

/** Runs the index pass and the transforms; returns rewritten texts for changed in-scope files. */
export const runCodemod = (input: CodemodInput): CodemodResult => {
  const infos = input.sources.map((source) => scanFile(source.file, source.text));
  const isEffectedPort = effectedPortMatcher(input.sources.map((source) => source.file));
  const index: FileIndex = new Map(infos.map((info) => [info.file, info]));
  const resolver = new Resolver(infos, input.packageDirs);

  // Keep reasons from references, keyed by `${file}#${name}`.
  const refReasons = new Map<string, Map<KeepReason, Array<string>>>();
  for (const info of infos) {
    for (const ref of info.refs) {
      for (const target of resolver.resolve(info, ref)) {
        const key = `${target.file}#${target.name}`;
        const reasons = refReasons.get(key) ?? new Map<KeepReason, Array<string>>();
        const reason = REF_REASON[ref.kind];
        reasons.set(reason, [...(reasons.get(reason) ?? []), ref.site]);
        refReasons.set(key, reasons);
      }
    }
  }

  const allowlisted = new Map(
    input.keepClass
      .filter((entry) => entry.brand === undefined)
      .map((entry) => [`${entry.file}#${entry.class}`, entry.reason])
  );
  const brandEntries = input.keepClass.filter((entry) => entry.brand !== undefined);
  const brandOverrideFor = (info: FileInfo, name: string): string | undefined => {
    const entry = brandEntries.find(
      (candidate) =>
        candidate.file === info.file &&
        (candidate.class === name || (candidate.class === "*" && declaredNamespaces(info).has(name)))
    );
    return entry === undefined ? undefined : entry.brand === "structural" ? "{}" : BRAND_ALT;
  };
  const results: Array<DeclResult> = [];
  const outputs: Array<{ file: string; text: string }> = [];
  const newSites: Array<{ target: string; site: string }> = [];
  const opaqueWithKeepReasons: Array<string> = [];

  const editsByFile = new Map<string, Array<Edit>>();
  for (const info of infos) {
    if (info.decls.length === 0) continue;
    const edits: Array<Edit> = [];
    editsByFile.set(info.file, edits);
    for (const decl of info.decls) {
      const name = decl.name ?? "<anonymous>";
      const key = `${info.file}#${name}`;
      const record = (outcome: Outcome, keepReasons: ReadonlyArray<KeepReason> = []): void => {
        results.push({ file: info.file, name, kind: decl.heritage.kind, outcome, keepReasons, line: decl.line });
      };
      if (info.generated) {
        record("skipped-generated");
        continue;
      }
      const isDataClass = decl.heritage.kind === "Class" || decl.heritage.kind === "TaggedClass";
      const staticSuper = !input.reverse && hasStaticSuperMember(decl.node);
      if (decl.heritage.kind === "Opaque" && !input.reverse && !allowlisted.has(key) && !staticSuper) {
        edits.push(...planIdentityNormalize(info, decl));
      }
      const override = brandOverrideFor(info, name);
      const currentBrand = decl.heritage.typeArgs[1];
      if (override !== undefined && currentBrand !== undefined) {
        const brandText = currentBrand
          .getText(info.sf)
          .replace(/\s+/g, " ")
          .replace(/;\s*\}/, " }");
        if (brandText !== override) {
          edits.push({ start: currentBrand.getStart(info.sf), end: currentBrand.end, text: override });
          record("brand-override", ["brand-override-exception"]);
        } else {
          record("already-branded", ["brand-override-exception"]);
        }
        continue;
      }

      if (decl.heritage.kind === "Opaque" && (input.reverse || allowlisted.has(key) || staticSuper)) {
        const reverse = planReverse(info, decl);
        if (reverse !== undefined) {
          edits.push(...reverse.edits);
          record(
            reverse.outcome,
            input.reverse
              ? []
              : [
                  ...(allowlisted.has(key) ? ["keep-class-allowlist" as const] : []),
                  ...(staticSuper ? ["static-super" as const] : []),
                ]
          );
          continue;
        }
      }
      if (decl.heritage.kind === "Opaque" && refReasons.has(key) && decl.heritage.typeArgs.length >= 2) {
        opaqueWithKeepReasons.push(`${key} (${[...(refReasons.get(key)?.keys() ?? [])].join(", ")})`);
      }

      if (isDataClass && decl.heritage.typeArgs.length >= 2) {
        // Transform 1: an explicit brand means the author already chose the shape.
        record("already-branded");
        continue;
      }
      if (isDataClass && !input.reverse) {
        const reasons = new Set<KeepReason>();
        if (isEffectedPort(info.file)) reasons.add("effected-port");
        if (hasInstanceMember(decl.node)) reasons.add("instance-member");
        if (hasStaticSuperMember(decl.node)) reasons.add("static-super");
        // Converting needs `S.Opaque` / `S.Struct` in scope; a named-import file only gets the brand.
        if (decl.heritage.ns === "") reasons.add("named-import");
        for (const reason of refReasons.get(key)?.keys() ?? []) reasons.add(reason);
        if (allowlisted.has(key)) reasons.add("keep-class-allowlist");
        if (decl.name === undefined || !ts.isClassDeclaration(decl.node)) reasons.add("unrecognized-shape");
        if (reasons.size === 0) {
          const plan = planConversion(index, info, decl, override);
          if (typeof plan !== "string") {
            edits.push(...plan.edits);
            record(plan.outcome);
            continue;
          }
          reasons.add(plan);
        }
        for (const site of refReasons.get(key)?.get("new-site") ?? []) newSites.push({ target: key, site });
        const brand = planBrand(index, info, decl, override);
        if (typeof brand === "string") {
          record(brand, [...reasons]);
        } else {
          edits.push(...brand);
          record("brand-added", [...reasons]);
        }
        continue;
      }

      const brand = planBrand(index, info, decl, override);
      if (typeof brand === "string") {
        record(brand);
      } else {
        edits.push(...brand);
        record("brand-added");
      }
    }
  }

  // JSDoc examples cannot `new` an S.Opaque (its constructor takes `never`): use `X.make(`.
  const finalShape = new Map<string, Set<"opaque" | "class">>();
  for (const result of results) {
    const opaque =
      result.outcome === "converted-class" ||
      result.outcome === "converted-tagged-class" ||
      (result.kind === "Opaque" && result.outcome !== "reverted-to-class");
    const scopeKey = `${packageDirOf(result.file, input.packageDirs) ?? result.file}#${result.name}`;
    const shapes = finalShape.get(scopeKey) ?? new Set<"opaque" | "class">();
    shapes.add(opaque ? "opaque" : "class");
    finalShape.set(scopeKey, shapes);
  }
  const isOpaqueIn = (file: string, name: string): boolean => {
    const shapes = finalShape.get(`${packageDirOf(file, input.packageDirs) ?? file}#${name}`);
    return shapes !== undefined && shapes.size === 1 && shapes.has("opaque");
  };
  for (const info of infos) {
    if (!/\bnew [A-Z]/.test(info.text)) continue;
    const docEdits = docExampleEdits(info, isOpaqueIn);
    if (docEdits.length === 0) continue;
    const edits = editsByFile.get(info.file) ?? [];
    edits.push(...docEdits);
    editsByFile.set(info.file, edits);
  }

  for (const info of infos) {
    const edits = editsByFile.get(info.file) ?? [];
    if (!input.inScope(info.file) || edits.length === 0) continue;
    const next = applyEdits(info.text, edits);
    if (next !== info.text) outputs.push({ file: info.file, text: next });
  }

  return { results, outputs, newSites, opaqueWithKeepReasons };
};

/** One schema-class declaration in the repo-wide class index used by `fixup.ts`. */
export interface SchemaClassEntry {
  readonly exported: boolean;
  readonly file: string;
  readonly name: string;
  /** `_tag` literal value for tagged shapes. */
  readonly tag: string | undefined;
  /** Every `S.tag(...)` discriminant field (including `_tag`) and its literal source text. */
  readonly tagFields: Readonly<Record<string, string>>;
}

const tagFieldsOfDecl = (info: FileInfo, decl: SchemaClassDecl): Record<string, string> => {
  const out: Record<string, string> = {};
  const tag = tagOfDecl(decl);
  if (tag !== undefined) out._tag = JSON.stringify(tag);
  const visit = (node: ts.Node): void => {
    if (
      ts.isPropertyAssignment(node) &&
      (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name)) &&
      ts.isCallExpression(node.initializer) &&
      ts.isPropertyAccessExpression(node.initializer.expression) &&
      node.initializer.expression.name.text === "tag" &&
      info.nsBindings.has(node.initializer.expression.expression.getText()) &&
      node.initializer.arguments[0] !== undefined
    ) {
      out[node.name.text] = node.initializer.arguments[0].getText(info.sf);
      return;
    }
    if (ts.isClassElement(node) && !ts.isPropertyDeclaration(node)) return;
    ts.forEachChild(node, visit);
  };
  for (const clause of decl.node.heritageClauses ?? []) visit(clause);
  return out;
};

const tagOfDecl = (decl: SchemaClassDecl): string | undefined => {
  const { kind, outer } = decl.heritage;
  const literalText = (node: ts.Expression | undefined): string | undefined =>
    node !== undefined && ts.isStringLiteral(node) ? node.text : undefined;
  if (kind === "TaggedClass" || kind === "TaggedError") return literalText(outer.arguments[0]);
  if (kind !== "Opaque") return undefined;
  let source = outer.arguments[0];
  while (source !== undefined && ts.isCallExpression(source)) {
    const callee = source.expression;
    if (ts.isPropertyAccessExpression(callee) && callee.name.text === "TaggedStruct") {
      return literalText(source.arguments[0]);
    }
    source = ts.isPropertyAccessExpression(callee) ? callee.expression : undefined;
  }
  return undefined;
};

/** Indexes every named schema-class declaration (export status and `_tag`). */
export const indexSchemaClasses = (
  sources: ReadonlyArray<{ readonly file: string; readonly text: string }>
): ReadonlyArray<SchemaClassEntry> =>
  sources.flatMap((source) => {
    if (!/\b(Class|TaggedClass|Error|TaggedError|Opaque)</.test(source.text)) return [];
    const info = scanFile(source.file, source.text);
    const listed = new Set<string>();
    for (const statement of info.sf.statements) {
      if (
        ts.isExportDeclaration(statement) &&
        statement.moduleSpecifier === undefined &&
        statement.exportClause !== undefined &&
        ts.isNamedExports(statement.exportClause)
      ) {
        for (const element of statement.exportClause.elements) listed.add((element.propertyName ?? element.name).text);
      }
    }
    return info.decls.flatMap((decl) =>
      decl.name === undefined
        ? []
        : [
            {
              file: source.file,
              name: decl.name,
              exported:
                listed.has(decl.name) ||
                (ts.getModifiers(decl.node as ts.ClassDeclaration) ?? []).some(
                  (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword
                ),
              tag: tagOfDecl(decl),
              tagFields: tagFieldsOfDecl(info, decl),
            },
          ]
    );
  });
