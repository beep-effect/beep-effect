const RESOLVE_SUFFIXES = ["", ".ts", ".tsx", "/index.ts", "/index.tsx"] as const;

const packageDirOf = (file: string, packageDirs: ReadonlyMap<string, string>): string | undefined => {
  let best: string | undefined;
  for (const dir of packageDirs.values()) {
    if (file.startsWith(`${dir}/`) && (best === undefined || dir.length > best.length)) best = dir;
  }
  return best;
};

class Resolver {
  readonly declsByName = new Map<string, Set<string>>();
  private readonly fileSet: ReadonlySet<string>;
  private readonly packageDirs: ReadonlyMap<string, string>;

  constructor(infos: ReadonlyArray<FileInfo>, packageDirs: ReadonlyMap<string, string>) {
    this.packageDirs = packageDirs;
    this.fileSet = new Set(infos.map((info) => info.file));
    for (const info of infos) {
      for (const name of info.declNames) {
        const files = this.declsByName.get(name) ?? new Set<string>();
        files.add(info.file);
        this.declsByName.set(name, files);
      }
    }
  }

  /** Candidate declaring files for `name` exported (directly or via barrel) by module `spec` imported from `from`. */
  private viaModule(from: string, spec: string, name: string): ReadonlyArray<string> {
    const candidates = [...(this.declsByName.get(name) ?? [])];
    if (candidates.length === 0) return [];
    let scopeDir: string | undefined;
    if (spec.startsWith(".")) {
      const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec)).replace(/\.(js|mjs)$/, "");
      for (const suffix of RESOLVE_SUFFIXES) {
        const target = `${base}${suffix}`;
        if (this.fileSet.has(target)) {
          if (candidates.includes(target)) return [target];
          scopeDir = path.posix.dirname(target);
          break;
        }
      }
      scopeDir ??= base;
    } else if (spec.startsWith("@/") || spec.startsWith("~/") || spec.startsWith("#")) {
      scopeDir = packageDirOf(from, this.packageDirs);
    } else {
      let bestName: string | undefined;
      for (const pkg of this.packageDirs.keys()) {
        if ((spec === pkg || spec.startsWith(`${pkg}/`)) && (bestName === undefined || pkg.length > bestName.length)) {
          bestName = pkg;
        }
      }
      if (bestName === undefined) return [];
      const packageDir = this.packageDirs.get(bestName);
      // A workspace package resolves only to its own declarations.
      return candidates.filter((candidate) => candidate.startsWith(`${packageDir}/`));
    }
    if (scopeDir === undefined) return candidates;
    const scoped = candidates.filter((candidate) => candidate.startsWith(`${scopeDir}/`));
    return scoped.length > 0 ? scoped : candidates;
  }

  /** Declaring `{ file, name }` targets a reference may denote (conservative on ambiguity). */
  resolve(info: FileInfo, ref: Ref): ReadonlyArray<{ readonly file: string; readonly name: string }> {
    const all = (name: string) => [...(this.declsByName.get(name) ?? [])].map((file) => ({ file, name }));
    const via = (spec: string, name: string) => this.viaModule(info.file, spec, name).map((file) => ({ file, name }));
    if (ref.qualifier === undefined) {
      if (info.declNames.has(ref.name)) return [{ file: info.file, name: ref.name }];
      const binding = info.imports.get(ref.name);
      if (binding === undefined || binding.imported === "*" || binding.imported === "default") return [];
      return via(binding.spec, binding.imported);
    }
    const head = ref.qualifier.split(".")[0] ?? ref.qualifier;
    if (head === "globalThis" || head === "window" || head === "self") return [];
    const binding = info.imports.get(head);
    if (binding !== undefined && binding.imported === "*" && head === ref.qualifier) return via(binding.spec, ref.name);
    if (binding !== undefined && !this.isWorkspaceSpec(binding.spec)) return [];
    return all(ref.name);
  }

  private isWorkspaceSpec(spec: string): boolean {
    if (spec.startsWith(".") || spec.startsWith("@/") || spec.startsWith("~/") || spec.startsWith("#")) return true;
    for (const pkg of this.packageDirs.keys()) {
      if (spec === pkg || spec.startsWith(`${pkg}/`)) return true;
    }
    return false;
  }
}

