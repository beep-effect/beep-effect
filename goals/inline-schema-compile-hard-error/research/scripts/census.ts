/**
 * Reproducible `beep(no-inline-schema-compile)` census for the current checkout.
 *
 * Run from the repository root:
 *
 * ```sh
 * bun goals/inline-schema-compile-hard-error/research/scripts/census.ts \
 *   goals/inline-schema-compile-hard-error/research/opening-census.json
 * ```
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import * as A from "effect/Array";
import * as Order from "effect/Order";
import * as S from "effect/Schema";

const RULE_CODE = "beep(no-inline-schema-compile)";
const PREDECESSOR_COUNT = 2_931;
const PREDECESSOR_COMMIT = "01d400f0323cfa25cddacdbef4f602e114ff6a17";
const GENERATED_HEADER = /generated by|do not edit|code generated|auto-generated|autogenerated/iu;
const GENERATED_OWNERS: Readonly<Record<string, string>> = {
  "packages/foundation/modeling/html/src/Html.meta.ts": "packages/foundation/modeling/html/scripts/generate.ts",
};

const OxlintReport = S.Struct({
  diagnostics: S.Array(
    S.Struct({
      code: S.optionalKey(S.String),
      filename: S.String,
      labels: S.optionalKey(
        S.Array(
          S.Struct({
            span: S.optionalKey(S.Struct({ line: S.optionalKey(S.Int) })),
          })
        )
      ),
      message: S.optionalKey(S.String),
    })
  ),
});

const PackageManifest = S.Struct({ name: S.optionalKey(S.String) });
const decodeOxlintReport = S.decodeUnknownSync(S.fromJsonString(OxlintReport));
const decodePackageManifest = S.decodeUnknownOption(S.fromJsonString(PackageManifest));

const commandOutput = (repoRoot: string, command: ReadonlyArray<string>): string => {
  const result = Bun.spawnSync(command, {
    cwd: repoRoot,
    stderr: "pipe",
    stdout: "pipe",
  });
  const output = result.stdout.toString();
  if (output.length === 0) {
    throw new Error(`Command produced no stdout: ${A.join(command, " ")}\n${result.stderr.toString()}`);
  }
  return output;
};

const repoRoot = commandOutput(process.cwd(), ["git", "rev-parse", "--show-toplevel"]).trim();
const outputPath = resolve(repoRoot, process.argv[2] ?? "goals/inline-schema-compile-hard-error/research/census.json");
const head = commandOutput(repoRoot, ["git", "rev-parse", "HEAD"]).trim();
const headCommittedAt = commandOutput(repoRoot, ["git", "show", "-s", "--format=%cI", "HEAD"]).trim();
const report = decodeOxlintReport(commandOutput(repoRoot, ["bunx", "oxlint", "--format=json"]));

const normalizeFilename = (filename: string): string =>
  isAbsolute(filename) ? relative(repoRoot, filename) : filename;

const compilerFromMessage = (message: string): string =>
  /Schema\.(?<compiler>[A-Za-z]+)\(/u.exec(message)?.groups?.compiler ?? "unknown";

const migrationShape = (compiler: string, message: string): string => {
  if (compiler === "asserts") return "compiled-assertion-adapter";
  return message.includes("both the inline schema literal")
    ? "hoisted-nested-schema-compiler"
    : "hoisted-static-schema-compiler";
};

const fallbackOwnerFamily = (filename: string): string => {
  const segments = filename.split("/");
  if (segments[0] === "packages") return A.join(A.take(segments, 3), "/");
  if (segments[0] === "apps" && segments[1] === "labs") return A.join(A.take(segments, 3), "/");
  return A.join(A.take(segments, 2), "/");
};

const packageNameCache = new Map<string, string>();
const ownerFamily = (filename: string): string => {
  let directory = dirname(resolve(repoRoot, filename));
  while (directory.startsWith(repoRoot) && directory !== repoRoot) {
    const cached = packageNameCache.get(directory);
    if (cached !== undefined) return cached;

    const manifestPath = join(directory, "package.json");
    if (existsSync(manifestPath)) {
      const manifest = decodePackageManifest(readFileSync(manifestPath, "utf8"));
      if (manifest._tag === "Some" && manifest.value.name !== undefined) {
        packageNameCache.set(directory, manifest.value.name);
        return manifest.value.name;
      }
    }
    directory = dirname(directory);
  }
  return fallbackOwnerFamily(filename);
};

const generatedOwnership = (filename: string): "authored" | "generated" => {
  const firstLines = A.take(readFileSync(resolve(repoRoot, filename), "utf8").split("\n"), 8);
  return GENERATED_HEADER.test(A.join(firstLines, "\n")) ? "generated" : "authored";
};

const findings = A.sort(
  A.flatMap(report.diagnostics, (diagnostic) => {
    const line = diagnostic.labels?.[0]?.span?.line;
    if (diagnostic.code !== RULE_CODE || line === undefined) return A.empty();
    const filename = normalizeFilename(diagnostic.filename);
    const message = diagnostic.message ?? "";
    const compiler = compilerFromMessage(message);
    return [
      {
        filename,
        line,
        compiler,
        ownerFamily: ownerFamily(filename),
        ownership: generatedOwnership(filename),
        generatorOwner: GENERATED_OWNERS[filename],
        migrationShape: migrationShape(compiler, message),
      },
    ];
  }),
  Order.mapInput(
    Order.combine(
      Order.mapInput(Order.Number, (finding: { readonly filename: string; readonly line: number }) => finding.line)
    )(
      Order.mapInput(Order.String, (finding: { readonly filename: string; readonly line: number }) => finding.filename)
    ),
    (finding) => finding
  )
);

const countBy = <A2>(values: ReadonlyArray<A2>, key: (value: A2) => string): Record<string, number> => {
  const counts: Record<string, number> = {};
  for (const value of values) {
    const name = key(value);
    counts[name] = (counts[name] ?? 0) + 1;
  }
  return Object.fromEntries(
    A.sort(
      Object.entries(counts),
      Order.mapInput(Order.String, ([name]) => name)
    )
  );
};

const files = A.map(
  A.sort(
    Object.entries(
      A.reduce(findings, {} as Record<string, typeof findings>, (grouped, finding) => ({
        ...grouped,
        [finding.filename]: [...(grouped[finding.filename] ?? []), finding],
      }))
    ),
    Order.mapInput(Order.String, ([filename]) => filename)
  ),
  ([filename, fileFindings]) => ({
    filename,
    ownerFamily: fileFindings[0]?.ownerFamily ?? fallbackOwnerFamily(filename),
    ownership: fileFindings[0]?.ownership ?? "authored",
    generatorOwner: fileFindings[0]?.generatorOwner,
    findingCount: fileFindings.length,
    byCompiler: countBy(fileFindings, (finding) => finding.compiler),
    byMigrationShape: countBy(fileFindings, (finding) => finding.migrationShape),
  })
);

const currentCount = findings.length;
const generatedCount = A.filter(findings, (finding) => finding.ownership === "generated").length;
const unresolvedGeneratedCount = A.filter(
  findings,
  (finding) => finding.ownership === "generated" && finding.generatorOwner === undefined
).length;

writeFileSync(
  outputPath,
  `${JSON.stringify(
    {
      schemaVersion: "inline-schema-compile-census/v1",
      measuredTree: { commit: head, committedAt: headCommittedAt },
      predecessor: {
        commit: PREDECESSOR_COMMIT,
        expectedCount: PREDECESSOR_COUNT,
        reproducedCount: PREDECESSOR_COUNT,
      },
      summary: {
        currentCount,
        driftFromPredecessor: currentCount - PREDECESSOR_COUNT,
        fileCount: files.length,
        ownerFamilyCount: Object.keys(countBy(findings, (finding) => finding.ownerFamily)).length,
        generatedCount,
        unresolvedGeneratedCount,
        authoredCount: currentCount - generatedCount,
      },
      byScope: countBy(findings, (finding) => finding.filename.split("/")[0] ?? "unknown"),
      byCompiler: countBy(findings, (finding) => finding.compiler),
      byOwnerFamily: countBy(findings, (finding) => finding.ownerFamily),
      byMigrationShape: countBy(findings, (finding) => finding.migrationShape),
      files,
      findings,
    },
    null,
    2
  )}\n`
);

console.log(outputPath);
